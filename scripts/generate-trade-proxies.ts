import { writeFileSync } from "node:fs";
import { fitTradeProxies, PACK, pack } from "./lib/shipyard-proxies";
import { tradeModelHash } from "./lib/shipped-trades";
import type { AuthoredTradeForm } from "../src/station-mesh";

const fitted = await fitTradeProxies();
const sources: Record<string, string> = {};
const data: Record<string, { hull: string }> = {};
for (const [form, { hull }] of Object.entries(fitted)) {
	sources[form] = tradeModelHash(form as AuthoredTradeForm);
	data[form] = { hull: pack(hull) };
	console.log(`${form}: ${hull.length} hull boxes`);
}
writeFileSync(
	"src/trade-proxies.ts",
	`/** Generated by scripts/generate-trade-proxies.ts from shipped trade models (node #1033). */\nexport const TRADE_PROXY_PACK = ${JSON.stringify(PACK)} as const;\nexport const TRADE_PROXY_SOURCES = ${JSON.stringify(sources)} as const;\nexport const TRADE_PROXIES = ${JSON.stringify(data)} as const;\n`,
);
