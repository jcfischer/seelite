/**
 * What a body is for rendering purposes.
 *
 * Includes display ships (#52). The generator retains its narrower
 * `PlacedBody["kind"]`; a display contact never joins the generated body list.
 */
/** `relay` is #43's pirate sensor relay: a contact, never a generated body,
 *  and a kind of its own so the Target panel and the marker label can name it.
 *  `cargo` is #324's canister, on the same footing for the same reason — the
 *  principal's ruling after the fifth playtest, when a canister was a HUD
 *  diamond that could not be selected and so had no readout to fly by. */
export type BodyKind =
	| "star"
	| "planet"
	| "moon"
	| "station"
	| "ship"
	| "relay"
	| "cargo";

export interface Body {
	id: string;
	/** Display-only label; every lookup continues to use `id`. */
	name: string;
	kind: BodyKind;
	stationType?: StationType;
	/** Sim-space position, kilometres, float64, star-centred (spec §7.4). */
	pos: Vec3;
	/** Physical radius in kilometres — scaled with the position in the far
	 *  layer, so the two must not drift apart. */
	radiusKm: number;
	/** Base colour. Emissive for a star, diffuse for everything else. */
	color: number;
	/**
	 * How this body is drawn, classified from the generator's own numbers.
	 *
	 * `undefined` for a station, which is the one body that is not a sphere.
	 *
	 * **Held here rather than derived in the renderer**, for the reason
	 * `color` is: the class is a function of `aAu`, `isGasGiant` and the star's
	 * luminosity, all of which live in `contents`, and a renderer that looked
	 * them up itself would be the second place that join is spelled. It stays
	 * display-only and it stays pure — `planet-appearance.ts` imports nothing
	 * but `system.ts`, so carrying it here does not put Three.js anywhere near
	 * this module.
	 */
	appearance?: PlanetAppearance;
}

export interface Ship {
	/** Sim-space position, kilometres, float64. */
	pos: Vec3;
	/** Kilometres per second. */
	vel: Vec3;
}

export interface System {
	/** What the galaxy knows about this system: name, polity, position in LY. */
	record: SystemRecord;
	/** Orbits and radii — time-independent. The generator's output, held so the
	 *  clock can be re-read against it every frame rather than regenerating. */
	contents: SystemContents;
	/** Those contents positioned at the world's `gameTime`. */
	bodies: Body[];
	/** The same bodies by id. Built once — the id set is fixed for a system's
	 *  lifetime, and `advanceSystem` runs every frame. */
	byId: Map<string, Body>;
}

export interface World {
	/** The world seed. Every stream in `rng.ts` derives from this one number. */
	seed: number;
	/**
	 * Seconds of simulation since the new game began.
	 *
	 * The authority for where every body is (spec §7.3), which is why it lives
	 * on the world rather than in the renderer's frame loop: a save carries it,
	 * and anything time-varying — market regeneration, legal-status decay —
	 * reads it rather than inventing its own clock.
	 *
	 * Never compressed (#10). Cruise is fictional FTL, not a time-scale hack.
	 */
	gameTime: number;
	/** Galaxy 0, held whole. 256 records is a few hundred kilobytes, and #11's
	 *  map wants exactly this object. */
	galaxy: Galaxy;
	system: System;
	ship: Ship;
}

/** A new game starts in galaxy 0 (spec §5.1). Which system within it is
 *  `startSystem`'s decision, not this module's. */
export const START_GALAXY = 0;

/** Rocky worlds. Picked by eye from the usual terrestrial range — scenery, not
 *  a claim about composition. */
const ROCKY_COLORS = [0xb08050, 0x8fae7a, 0xc0a080, 0x9b6b53, 0x7f8b94];
/** Gas giants: banded pastels, deliberately lighter than the rocky set so the
 *  two read apart at a glance in a system that has both. */
const GIANT_COLORS = [0xd8c49a, 0xc9a26b, 0xb8c4d8, 0xe0d2b4];
/** Moons: grey, and narrow. A moon that read as colourful as its planet would
 *  compete with it for attention it has not earned. */
const MOON_COLORS = [0x9a9a9a, 0xb0aaa4, 0x86867e];
/**
 * Stations by type, so the type is legible before anything else about the
 * station is. #9 owns their actual geometry.
 *
 * Keyed on `StationType`, not on the body id, and the difference is a compile
 * error rather than a style preference: a `Record<string, number>` keyed on ids
 * needs a fallback for the unmatched case, and that fallback silently paints a
 * renamed or newly added station the same grey as a trade post. `Record<
 * StationType, …>` has no unmatched case to fall back from — adding a fourth
 * station type stops the build until this table answers for it.
 */
const STATION_COLORS: Record<StationType, number> = {
	trade: 0x9aa6b2,
	refinery: 0xb08a5a,
	shipyard: 0x8fc0c0,
	// An industrial ochre, and deliberately the warmest of the four: an outpost
	// is a small machine in the dark, and the type's whole job at range is to
	// not be mistaken for a station you can trade at.
	outpost: 0xb08a52,
};

/**
 * A body's colour, from its identity rather than from its draw order.
 *
 * Seeded through `mix(systemSeed, hashId(body.id))` on its own generator rather
 * than drawn from `DOMAIN.BODIES`, and that is the same rule the `ARRIVAL` tag
 * was added for: replaying a stream the generator already consumed correlates
 * the result with whatever that stream produced. Here the consequence would only
 * be ugly rather than wrong, but a private generator costs nothing and needs no
 * argument.
 *
 * **The identity is the id, not the array index.** An earlier version mixed the
 * position in `placeBodies`' output, which is draw order wearing identity's
 * name: a planet gaining a moon shifts every later index and re-colours the rest
 * of the system. The id is stable against exactly that.
 *
 * Takes the whole system rather than four positional arguments — two of which
 * were `number` and adjacent, one slip from silently swapping the seed and the
 * index.
 */
function colorFor(
	body: PlacedBody,
	record: SystemRecord,
	contents: SystemContents,
): number {
	if (body.kind === "star") return contents.star.color;
	if (body.kind === "station") {
		const station = contents.stations.find((s) => s.id === body.id);
		// A body in `placeBodies`' output that is not in `contents` is not a colour
		// problem, it is the two having disagreed about what is in the system — so
		// it throws rather than picking a default and carrying on.
		if (!station) throw new Error(`station ${body.id} is not in the contents`);
		return STATION_COLORS[station.type];
	}
	const rand = seededRand(mix(record.seed, hashId(body.id)));
	if (body.kind === "moon")
		return MOON_COLORS[Math.floor(rand() * MOON_COLORS.length)];
	// Same rule as the station branch, for the same reason. Falling through to
	// the rocky palette on an unmatched id would paint a gas giant as a rocky
	// world and report nothing.
	const planet = contents.planets.find((p) => p.id === body.id);
	if (!planet) throw new Error(`planet ${body.id} is not in the contents`);
	const palette = planet.isGasGiant ? GIANT_COLORS : ROCKY_COLORS;
	return palette[Math.floor(rand() * palette.length)];
}

/**
 * A body id as a number, for `mix`.
 *
 * FNV-1a, because it needs to be a stable function of the string and nothing
 * more — this feeds a colour, not a position, and no property of the world
 * depends on its distribution.
 */
function hashId(id: string): number {
	let h = 0x811c9dc5;
	for (let i = 0; i < id.length; i++) {
		h ^= id.charCodeAt(i);
		h = Math.imul(h, 0x01000193);
	}
	return h >>> 0;
}

/** Generate a system's contents and position them at `gameTime`. */
export function makeSystem(record: SystemRecord, gameTime: number): System {
	const contents = generateContents(record);
	const bodies = placeBodies(contents, gameTime).map((b) => ({
		id: b.id,
		name: b.name,
		kind: b.kind,
		stationType: b.stationType,
		pos: b.pos,
		radiusKm: b.radiusKm,
		color: colorFor(b, record, contents),
		appearance: appearanceOf(b, contents),
	}));
	return {
		record,
		contents,
		bodies,
		byId: new Map(bodies.map((b) => [b.id, b])),
	};
}

/**
 * Move a system's bodies to where they are at `gameTime`.
 *
 * Positions are overwritten in place rather than the array being rebuilt, and
 * the reason is the renderer: it holds one mesh per body id, so a fresh array
 * every frame would either force a lookup per body or invite the id-to-mesh map
 * to drift.
 *
 * **Written by id, not by index.** The index form was a positional contract
 * between two modules enforced only by a test — a `placeBodies` that ever
 * filtered or sorted its output (skipping a destroyed station, say) would keep
 * running and assign positions to the wrong bodies, which reads on screen as
 * planets teleporting rather than as an error. Keying by id makes that a throw.
 *
 * The lookup is built **once**, in `makeSystem`, not per frame: the id set is
 * fixed for the lifetime of a system, so rebuilding a `Map` sixty times a second
 * would be paying for a structure that never changes.
 */
export function advanceSystem(system: System, gameTime: number): void {
	const placed = placeBodies(system.contents, gameTime);
	if (placed.length !== system.byId.size) {
		throw new Error(
			`placeBodies returned ${placed.length} bodies, system holds ${system.byId.size}`,
		);
	}
	for (const p of placed) {
		const body = system.byId.get(p.id);
		if (!body) throw new Error(`placeBodies produced unknown body ${p.id}`);
		body.pos = p.pos;
	}
}

/**
 * The body a station orbits, or `null` — #30's arrival rule reads it.
 *
 * Named for stations because it answers for stations and nothing else: it looks
 * only in `contents.stations`, so the gap below is in the signature rather than
 * only in this comment.
 *
 * Only a station has one, because only a station is placed relative to another
 * body. A *planet* selected as a target returns null and is right to: it is a
 * mass in its own right, and cruise to it must still be stopped by it, which is
 * what leaves the ship above its surface rather than inside it.
 *
 * A **moon** returns null and is not so clearly right. `advanceCruise` counts
 * only stars and planets as masses (#10 §2.1), so a moon is neither an obstacle
 * nor a host — and a moon low over a large planet is the same geometry #30 is
 * about, unmeasured because nothing targets a moon yet.
 *
 * One function rather than three copies of `station.parentId`: the renderer, the
 * measurement sweep and the browser probe all ask this question, and a rule the
 * instrument states slightly differently from the game is an instrument that can
 * go green on a game that is wrong.
 */
export function stationHostIdOf(system: System, id: string): string | null {
	const station = system.contents.stations.find((s) => s.id === id);
	return station ? station.parentId : null;
}

/**
 * How fast a body is moving through sim space, km/s.
 *
 * Composed the same way `placeBodies` composes positions — a station's velocity
 * is its parent planet's plus its own around it — because the two have to agree
 * or the ship would be told to match a frame the body is not in.
 *
 * Here rather than in `system.ts` because it needs the *contents* to resolve a
 * parent, which is what this module already holds; `system.ts` supplies the
 * per-orbit derivative and this composes it. The star does not move: system
 * frames are star-centred (spec §7.4), so its velocity is zero by construction
 * rather than by measurement.
 */
export function bodyVelocity(
	system: System,
	id: string,
	gameTime: number,
): Vec3 {
	const { contents } = system;
	if (id === contents.star.id) return v3();
	const planet = contents.planets.find((p) => p.id === id);
	if (planet) return velocityOnOrbit(planet.orbit, gameTime);
	for (const p of contents.planets) {
		const moon = p.moons.find((m) => m.id === id);
		if (moon) {
			return add(
				velocityOnOrbit(p.orbit, gameTime),
				velocityOnOrbit(moon.orbit, gameTime),
			);
		}
	}
	const station = contents.stations.find((s) => s.id === id);
	if (station) {
		const own = velocityOnOrbit(station.orbit, gameTime);
		if (!station.parentId) return own;
		const parent = contents.planets.find((p) => p.id === station.parentId);
		// A parent that is not in the contents is the two having disagreed about
		// what is in the system, which is the same throw `colorFor` makes rather
		// than quietly returning a velocity in the wrong frame.
		if (!parent)
			throw new Error(`station ${id} orbits unknown ${station.parentId}`);
		return add(velocityOnOrbit(parent.orbit, gameTime), own);
	}
	throw new Error(`no body ${id} in this system`);
}

/**
 * Conservative acceleration magnitude for a body's composed circular motion.
 *
 * A moon or planet-hosted station has two rotating terms.  Their acceleration
 * vectors need not align, so summing magnitudes is the safe bound.  The star is
 * fixed in the system frame.  This mirrors `bodyVelocity`'s ownership and its
 * missing-parent failure rather than inventing a second lookup policy.
 */
export function bodyAccelerationBound(system: System, id: string): number {
	const { contents } = system;
	if (id === contents.star.id) return 0;
	const planet = contents.planets.find((p) => p.id === id);
	if (planet) return accelerationBoundOnOrbit(planet.orbit);
	for (const p of contents.planets) {
		const moon = p.moons.find((m) => m.id === id);
		if (moon)
			return (
				accelerationBoundOnOrbit(p.orbit) + accelerationBoundOnOrbit(moon.orbit)
			);
	}
	const station = contents.stations.find((s) => s.id === id);
	if (station) {
		const own = accelerationBoundOnOrbit(station.orbit);
		if (!station.parentId) return own;
		const parent = contents.planets.find((p) => p.id === station.parentId);
		if (!parent)
			throw new Error(`station ${id} orbits unknown ${station.parentId}`);
		return own + accelerationBoundOnOrbit(parent.orbit);
	}
	throw new Error(`no body ${id} in this system`);
}

/**
 * Where a station's aperture points, and how far its slot has rotated
 * (`docking.md` §4.1, §5).
 *
 * **In sim, not in the renderer.** The repo's rule is that the scene graph is
 * display only and nothing reads a position back out of an `Object3D`; without
 * this function the obvious implementation of check 4 (the roll match, #9's own
 * node) reads the slot's phase off the rendered station, which makes a docking
 * check depend on frame timing. The renderer mirrors what this returns.
 *
 * The axis is a *unit* vector in sim space:
 *
 * - `parent` — from the station toward the planet it orbits, 1984's "face
 *   nearest the planet". It swings as the station goes round, which is the
 *   whole reason it is computed per call rather than stored at generation.
 * - `outward` — radially away from the star for the star-centric refinery,
 *   which has no parent to face. System frames are star-centred (§7.4), so
 *   that is the station's own position normalised.
 *
 * The degenerate case — a station exactly on top of what it faces — cannot
 * arise from the generator (station orbits are 400–2,000 km up) but is answered
 * rather than left to produce a `NaN` quaternion in the renderer.
 */
export interface StationPose {
	/** Unit vector along the aperture axis, sim space. */
	axis: Vec3;
	/** Slot rotation about that axis, radians in [0, 2π). Always 0 for a pad. */
	phaseRad: number;
	/**
	 * The slot's phase-zero direction — where `across` points at phase zero
	 * (#126).
	 *
	 * **The station's own along-track direction**, which is its velocity about
	 * whatever it orbits, with the parent's motion removed. Two properties make
	 * it the right reference and nothing else here has both: it is perpendicular
	 * to the axis by construction on a circular orbit, and it turns *smoothly*
	 * as the axis swings. `docking.ts`'s old `anyPerpendicular` had the first
	 * and not the second — it picks its seed on a `< 0.9` branch, so the
	 * reference jumps, and a renderer sharing it snapped the drawn hull round.
	 *
	 * It lives here rather than in `docking.ts` because this is where the orbit
	 * is. The arrow still points one way: `docking.ts` imports neither this
	 * module nor anything that would need it.
	 */
	reference: Vec3;
}

/**
 * The generated station behind a placed body, or a throw.
 *
 * A join between the two representations of one thing — `contents.stations` and
 * the placed `Body` — and it belongs here for the same reason `stationPose`
 * does: the renderer holds neither authoritatively, and a body that is not in
 * the contents is the generator and the placement having disagreed, which is
 * the error `colorFor` already throws on rather than defaulting past.
 */
export function stationOf(system: System, id: string): Station {
	const station = system.contents.stations.find((s) => s.id === id);
	if (!station) throw new Error(`station ${id} is not in the contents`);
	return station;
}

export function stationPose(
	system: System,
	stationId: string,
	gameTime: number,
): StationPose {
	const station = stationOf(system, stationId);
	const body = system.byId.get(stationId);
	if (!body) throw new Error(`station ${stationId} has no placed body`);

	const geometry = STATION_GEOMETRY[station.type];
	let toward: Vec3;
	if (geometry.axis === "parent") {
		const parent = station.parentId ? system.byId.get(station.parentId) : null;
		// Same throw `bodyVelocity` makes: a parent missing from the system is the
		// generator and the placement having disagreed, not a geometry question.
		if (!parent)
			throw new Error(
				`station ${stationId} orbits unknown ${station.parentId}`,
			);
		toward = sub(parent.pos, body.pos);
	} else {
		toward = body.pos;
	}

	const len = length(toward);
	const axis = len === 0 ? v3(1, 0, 0) : scale(toward, 1 / len);
	// **The station's own orbital velocity**, not `bodyVelocity`'s. The parent's
	// motion is thirty kilometres a second against the station's few, and it is
	// not perpendicular to this axis — a reference built from the sum would pass
	// through zero twice an orbit, which is the discontinuity #126 exists to be
	// rid of. Its own velocity about whatever it orbits is perpendicular to the
	// radius by construction, and the radius is this axis.
	const along = velocityOnOrbit(station.orbit, gameTime);
	const perpendicular = sub(along, scale(axis, dot(along, axis)));
	const perpendicularLen = length(perpendicular);
	// **A fraction of the velocity, not an exact zero.** The perpendicular
	// component is the whole velocity for a `parent`-axis station, whose axis is
	// its own orbital radius — but an `outward`-axis station's axis points away
	// from the *star*, and a shrinking-but-nonzero component would be normalised
	// back to unit length, amplifying whatever noise was left. That is a
	// discontinuous reference wearing a continuous one's clothes, which is the
	// failure #126 exists to remove. A thousandth of the speed is far below
	// anything a circular orbit produces and far above the rounding.
	const usable = perpendicularLen > length(along) * 1e-3;
	return {
		axis,
		phaseRad: slotPhaseRad(station.spinRpm, gameTime),
		// A station at rest in its own frame has no along-track direction. It
		// cannot happen — every orbit here has a period — and the fallback is
		// the old arbitrary perpendicular rather than a `NaN` basis.
		reference: usable
			? scale(perpendicular, 1 / perpendicularLen)
			: anyPerpendicularTo(axis),
	};
}

/** A direction not parallel to `a`, for the cases the along-track reference
 *  cannot serve: a station with no orbital motion, or one whose motion is along
 *  its own aperture axis. Discontinuous by construction — which is exactly why
 *  it is a fallback and not the rule (#126). */
function anyPerpendicularTo(a: Vec3): Vec3 {
	const seed =
		Math.abs(a.x) < 0.9
			? v3(1, 0, 0)
			: Math.abs(a.y) < 0.9
				? v3(0, 1, 0)
				: v3(0, 0, 1);
	const c = cross(a, seed);
	return scale(c, 1 / length(c));
}

/**
 * Build a world at a named galaxy, system and clock — the load path's half of
 * construction (#90).
 *
 * A save records all three, and none is what a new game has. `jumpWorldTo`
 * **throws** on a destination in another galaxy, deliberately: `World.galaxy`
 * is one galaxy held whole and crossing one is the Galactic Hyperdrive, a
 * different act at a different price. So a save taken in galaxy 3 cannot be
 * reached by constructing and jumping; it needs a world built for that galaxy
 * from the start, which is this.
 *
 * **The ship lands at the arrival point, and a caller with a saved position
 * overwrites it.** That is not a default standing in for a missing feature: a
 * restore with no flight record — a `lastDocked` checkpoint, a future migration
 * — needs somewhere legitimate to be, and the arrival point is where every
 * other entry to a system puts a ship.
 *
 * `makeWorld` is a call to this rather than a second construction path beside
 * it. Two paths is how the start system and the load path drift apart, and the
 * drift would be invisible: both produce a plausible world.
 */
export function restoreWorld(
	seed: number,
	galaxyIndex: number,
	systemIndex: number,
	gameTime: number,
): World {
	if (!Number.isInteger(galaxyIndex) || galaxyIndex < 0 || galaxyIndex > 7)
		throw new Error(`restoreWorld: ${galaxyIndex} is not a galaxy index`);
	if (!Number.isFinite(gameTime) || gameTime < 0)
		throw new Error(`restoreWorld: ${gameTime} is not a clock`);
	const galaxy = generateGalaxy(seed, galaxyIndex);
	const record = galaxy.systems[systemIndex];
	if (!record)
		throw new Error(
			`restoreWorld: galaxy ${galaxyIndex} has no system ${systemIndex}`,
		);
	// The clock reaches `makeSystem`, so the bodies are placed where it puts
	// them. Building at zero and assigning `gameTime` afterwards would pass
	// every field check and leave every planet an orbit out of date.
	const system = makeSystem(record, gameTime);
	return {
		seed,
		gameTime,
		galaxy,
		system,
		ship: {
			pos: arrivalPoint(record, system.contents, null, gameTime),
			vel: v3(),
		},
	};
}

export function makeWorld(seed: number): World {
	return restoreWorld(
		seed,
		START_GALAXY,
		startSystem(generateGalaxy(seed, START_GALAXY)).index,
		0,
	);
}

/**
 * A new game at a system the caller named, instead of at `startSystem`
 * ([#432](https://github.com/jcfischer/seelite/issues/432)).
 *
 * **A new game, elsewhere** — that is the whole difference, and it is why this
 * is a second *name* for `restoreWorld` rather than a second construction path
 * beside it: galaxy 0, clock 0, the ship on the arrival point, nothing carried
 * over. A build that kept the start system's arrival point while swapping in the
 * named system's bodies would produce a world that looks whole and is on the
 * wrong star, which is what `tests/world-restore.test.ts` holds.
 *
 * `?system=` boots through here. What such a boot may write is §11.6's ruling and
 * `BootPlan.writesNothing`'s answer, not this function's: a world builder has no
 * storage reach, so a promise made here is one nothing keeps.
 */
export function makeWorldAtSystem(seed: number, systemIndex: number): World {
	return restoreWorld(seed, START_GALAXY, systemIndex, 0);
}

/**
 * Take a world to another system — the act §8 describes and nothing has ever
 * performed (#187).
 *
 * ## What moves, and in what order
 *
 * The system is **replaced**, not edited: a new `System` from `makeSystem`, with
 * its own `contents`, its own `bodies` and its own `byId`. Editing the old one
 * in place was never on the table — a system's body set is its identity here,
 * and `advanceSystem` throws on a count mismatch precisely so that a system
 * quietly gaining a moon is an error rather than a drift.
 *
 * The ship lands at `arrivalPoint` with a **non-null `originPos` for the first
 * time in this repo's life**. §7.4's inbound bearing is
 * `normalize(p_origin − p_this)` in galaxy coordinates, so what is handed in is
 * the *origin system's* position in light years — not the ship's position in
 * kilometres, which is a different space and would produce a bearing that is
 * deterministic, well-formed and meaningless.
 *
 * ## The clock, and why it is not touched here
 *
 * **Sim time is never compressed (#10), and this node does not argue against
 * it.** The wind-up is flown: §8's few seconds pass in normal flight with the
 * ship vulnerable, so those seconds are already in the clock by the time this
 * runs, on the ordinary `stepWorld` path with the bodies moving under them. The
 * transition itself costs no sim time, because no ratified figure says how long
 * witchspace takes and inventing one here would settle an economy question by
 * accident: `market.ts` records that Elite re-rolled the fluctuation byte on
 * every jump while seelite's market is `f(seed, epoch)`, so **the clock is the
 * only thing that re-rolls a market**, and a clock advance sized to cross
 * #25's 30-minute epoch would make every jump a market reset that #25 measured
 * nothing against.
 *
 * What that costs is worth stating rather than leaving to be discovered: an
 * interstellar run costs ~3 s of game time per jump, so #7's 291 Cr
 * interstellar premium is a premium on *distance* and not on time, and jumping
 * is not a way to wait a market out. The other half is narrower than it first
 * read here: an out-and-back pair returns to the deficit **row** it left,
 * because the carrier key moves with the ship and the clock does not advance —
 * and that is all `tests/world-jump.test.ts` asserts. Whether it closes the
 * farm is a claim about a *price*, and a deficit row is not a price; nothing
 * headless here runs `stockResponse` across a jump. `galaxy-generation.md` §8.1
 * carries the same retraction, and #191's buy-back pump is the live case of a
 * market outcome nobody has measured.
 * If a witchspace duration is ever ratified, this function is the one place it
 * goes.
 *
 * ## What it refuses
 *
 * A destination in another galaxy. Galaxies are a namespace (#6) and crossing
 * one is the Galactic Hyperdrive (`galaxy-generation.md` §2), which is a
 * different act at a different price with different consequences for saved
 * state — `world.galaxy` is held whole and every saved fact is keyed on its
 * index. It throws rather than returning a refusal because the *range* refusal
 * belongs to `planJump`, which the caller has already run: reaching here with a
 * foreign record is a bug in the caller, not a move the player made.
 */
export function jumpWorldTo(world: World, to: SystemRecord): void {
	if (to.galaxy !== world.galaxy.index) {
		throw new Error(
			`jumpWorldTo: ${to.name} is in galaxy ${to.galaxy}, world is in ${world.galaxy.index}`,
		);
	}
	// Read before the system is replaced. This is the one line that makes
	// §7.4's bearing mean anything, and it is a galaxy-space position.
	const originPos = world.system.record.pos;
	world.system = makeSystem(to, world.gameTime);
	world.ship.pos = arrivalPoint(
		to,
		world.system.contents,
		originPos,
		world.gameTime,
	);
	// At rest in the star's frame, which is the frame the arrival point is
	// stated in. Carrying the origin system's velocity across would be carrying
	// a number from a coordinate system that no longer exists.
	world.ship.vel = v3();
}

/**
 * #5's assist cap, km/s — the speed assisted flight tops out at.
 *
 * It lives here, in the flight model, rather than beside the code that reads it
 * most: cruise's exit clamp (#10 §1) is stated *against* this number, and a cap
 * defined in `cruise.ts` would have the third regime deciding what the first
 * two are allowed to do.
 */
export const ASSIST_CAP_KMS = 2.0;

/**
 * The **baseline hull's** thrust, km/s². Tuned in #5's prototype so a 40 km
 * station approach takes about twenty seconds.
 *
 * Every other hull's is `thrustMN / massT` (#26's D5), and the courier's pair —
 * 120 MN over 60 t — is these 2.0 exactly, so the number #5 flew is still the
 * number the baseline hull flies. It stays exported because it is the reference
 * every derived figure below is stated against, not because anything integrates
 * with it.
 *
 * (The comment here read "about 0.2 g" until #181. 2 km/s² is 2,000 m/s², a
 * little over 200 g — the prose was three orders of magnitude out, in a line
 * whose only job was to state a magnitude, and nothing read it.)
 */
export const REFERENCE_THRUST_KMS2 = 2.0;

/**
 * How fast the assist kills sideways drift on the **baseline hull**: an
 * e-folding time in seconds.
 *
 * This is the whole difference between the two regimes, so it is the one number
 * that decides whether assisted flight feels like a plane or like a puck. Short
 * enough that a turn ends pointed where you are going; long enough that a hard
 * turn still slides, which is what stops the assist from reading as being on
 * rails.
 *
 * It scales **inversely with acceleration** across the roster, because the
 * assist removes drift with the same drive it accelerates with: a hull with half
 * the thrust-to-mass takes twice as long to wipe the same sideways velocity.
 * That is a derivation rather than a second tuning surface, which is the point —
 * D5 says mass and thrust are the hull properties, so nothing else may be one.
 */
export const REFERENCE_ASSIST_LATERAL_TAU_S = 1.2;

/**
 * How fast the ship is turning, radians per second, about its own axes.
 *
 * Rotation has **inertia**, and that is not a flourish: the first version set
 * the rate directly from the key state, so a turn began and ended on the frame
 * a key went down or up. The principal's words for it were that leaving a key
 * "stops any motion immediately, not a gentle way of easing out" — which is the
 * difference between 1984's fixed-rate turret and every space sim since.
 */
export interface Angular {
	pitch: number;
	yaw: number;
	roll: number;
}

/** Peak rate on each axis for the **baseline hull**, radians per second. Roll is
 *  faster because it moves nothing on screen but the horizon. */
export const REFERENCE_ANGULAR_MAX: Angular = {
	pitch: 0.9,
	yaw: 0.9,
	roll: 1.4,
};

/**
 * Angular acceleration for the **baseline hull**, radians per second².
 *
 * About a third of a second from rest to peak rate on the pitch and yaw axes —
 * fast enough that the ship answers the stick, slow enough that the answer is
 * something you feel arrive.
 */
export const REFERENCE_ANGULAR_ACCEL = 3.0;

/**
 * How quickly the assist stops a turn once the stick is released: an e-folding
 * time in seconds.
 *
 * Only with the assist **on**. With it off the ship keeps tumbling, which is
 * what Newtonian rotation means and what the assist-off regime is for — and it
 * is the second place (after lateral drift) where the two regimes visibly part.
 *
 * The **baseline hull's** figure; like the lateral one it scales inversely with
 * the hull's angular authority, so a heavier ship takes longer to stop turning.
 */
export const REFERENCE_ANGULAR_DAMP_TAU_S = 0.28;

/**
 * Everything a hull's handling is, as one struct — #26's D5 made concrete.
 *
 * `stepFlight` and `stepAngular` take one of these rather than reading module
 * constants, which is the whole of what makes a freighter fly differently from
 * an interceptor. **It is a parameter and not a default**: a default here would
 * let a caller that forgot to name a hull silently fly the courier, and the two
 * are indistinguishable in a diff.
 *
 * The assist **cap** is deliberately not in it. 2 km/s is the game's one combat
 * speed — the map's "nothing is crossable at combat speeds" is stated against
 * it and #10's cruise exit clamps to it — so a per-hull top speed would move a
 * constraint two other nodes are written on. What varies is how fast a hull
 * *reaches* the cap and how sharply it turns, which is what D5's "a freighter is
 * sluggish and an interceptor is sharp" is about: same drive tech, different
 * mass.
 */
export interface FlightPerformance {
	/** Linear acceleration along the nose, km/s² — `thrustMN / massT`. */
	thrustKms2: number;
	/** The assist's drift-removal e-folding time, seconds. */
	assistLateralTauS: number;
	/** Peak rate on each axis, radians per second. */
	angularMax: Angular;
	/** Angular acceleration, radians per second². */
	angularAccel: number;
	/** How fast the assist stops a turn, seconds. */
	angularDampTauS: number;
}

/**
 * A hull's handling, derived from its mass, its thrust and its length.
 *
 * Three derivations and no free parameters, which is what keeps D5 honest — the
 * table declares two numbers per hull and everything a pilot feels comes out of
 * them:
 *
 * - **Linear acceleration** is `thrustMN / massT`. Meganewtons over tonnes is
 *   km/s² exactly, which is why those units and not others.
 * - **Angular authority** scales as `acceleration / length`. Thrusters sit at
 *   the extremities, so the couple they make is `thrust × length`, while the
 *   pitch and yaw inertia goes as `mass × length²`; the length cancels once and
 *   what is left is `(thrust / mass) / length`. A longer, heavier hull is
 *   therefore slower to turn *and* slower to start turning, which is the whole
 *   of what "sluggish" means.
 *
 *   **Roll takes the same factor, and that is a simplification stated rather
 *   than derived.** Roll inertia goes as the beam and not the length, so the
 *   physics above does not reach it; what the roster gets is one angular
 *   authority per hull, scaled by the pitch and yaw figure. A separate roll term
 *   would be a fourth number for a difference no check in the repo can currently
 *   see, and the place it would first matter is a hull whose beam and length
 *   disagree far more than any of these eleven do.
 * - **Both e-folding times** scale inversely with the authority they express:
 *   the lateral one with linear acceleration, the angular one with angular.
 *
 * The courier reproduces #5's tuned figures exactly rather than nearly — its
 * ratio is the reference divided by itself — so the baseline hull is not
 * retuned by this node at all.
 */
export function flightPerformance(id: HullId): FlightPerformance {
	const spec = HULL_SPECS[id];
	const reference = HULL_SPECS[PLAYER_BASELINE_HULL];
	const thrustKms2 = spec.thrustMN / spec.massT;
	const referenceThrustKms2 = reference.thrustMN / reference.massT;
	// The turn-rate ratio, normalised so the baseline hull is exactly 1.
	const agility =
		thrustKms2 /
		spec.env.lengthKm /
		(referenceThrustKms2 / reference.env.lengthKm);
	return {
		thrustKms2,
		assistLateralTauS:
			(REFERENCE_ASSIST_LATERAL_TAU_S * referenceThrustKms2) / thrustKms2,
		angularMax: {
			pitch: REFERENCE_ANGULAR_MAX.pitch * agility,
			yaw: REFERENCE_ANGULAR_MAX.yaw * agility,
			roll: REFERENCE_ANGULAR_MAX.roll * agility,
		},
		angularAccel: REFERENCE_ANGULAR_ACCEL * agility,
		angularDampTauS: REFERENCE_ANGULAR_DAMP_TAU_S / agility,
	};
}

/**
 * One frame of rotation: the rates the renderer then applies to the quaternion.
 *
 * Pure, and here rather than in the renderer, for the same reason the flight
 * model is: it is dynamics, it decides how the ship *feels*, and something that
 * load-bearing should be checkable without opening a browser. The orientation
 * itself stays in the renderer — a quaternion is a thing Three.js already has a
 * good type for, and this module holds no quaternion of its own.
 *
 * `command` is the stick, −1…1 per axis. `impulse` is the mouse: a relative
 * pointer delta is not a stick position, it is a nudge, so it adds straight to
 * the rate and is then subject to the same damping.
 *
 * `perf` is the hull's, and it is required rather than defaulted for the reason
 * `FlightPerformance` states.
 */
export function stepAngular(
	rates: Angular,
	command: Angular,
	impulse: Angular,
	assist: boolean,
	dt: number,
	perf: FlightPerformance,
): Angular {
	if (dt <= 0) return rates;
	const decay = Math.exp(-dt / perf.angularDampTauS);
	const axis = (rate: number, want: number, kick: number, max: number) => {
		let next = rate + kick;
		if (want !== 0) {
			// Toward the commanded rate at a bounded acceleration — the ease-in.
			const target = clamp(want, -1, 1) * max;
			next += clamp(
				target - next,
				-perf.angularAccel * dt,
				perf.angularAccel * dt,
			);
		} else if (assist) {
			// The ease-*out*, which is the half that was missing.
			next *= decay;
		}
		return clamp(next, -max, max);
	};
	return {
		pitch: axis(
			rates.pitch,
			command.pitch,
			impulse.pitch,
			perf.angularMax.pitch,
		),
		yaw: axis(rates.yaw, command.yaw, impulse.yaw, perf.angularMax.yaw),
		roll: axis(rates.roll, command.roll, impulse.roll, perf.angularMax.roll),
	};
}

/**
 * What the player is asking the ship to do this frame.
 *
 * `nose` is a unit vector in sim space — orientation lives in the renderer (see
 * the module docstring), so the flight model is handed the direction rather
 * than the quaternion. `throttle` is 0…1 and means different things in the two
 * regimes, which is the point of the flag beside it.
 */
export interface FlightControl {
	nose: Vec3;
	throttle: number;
	/** #5's flight assist, a player toggle defaulting on. */
	assist: boolean;
	/**
	 * The frame the ship flies in, across this step. Omit for the star's frame,
	 * which is what the sim's coordinates are stated in.
	 *
	 * This exists because #14 flew an arrival and could not stay at it. Sim
	 * space is star-centred, so "stopped" means stopped relative to the star —
	 * but a station on a 1 AU orbit is doing ~30 km/s, fifteen times the assist
	 * cap. Cutting the throttle beside one therefore *pushes off* it at orbital
	 * speed, and nothing in normal flight can catch it again. Every space game
	 * that has stations solves this somehow; here the frame is passed in, and
	 * the renderer picks the nearest body as the local one.
	 *
	 * **Both regimes share the frame's acceleration, and only the assist holds
	 * its velocity (#529).** See `FrameMotion`.
	 */
	frame?: FrameMotion;
}

/**
 * A frame's velocity at the two ends of one step, km/s.
 *
 * A frame is a body on an orbit, so it **accelerates** — a trade station at a
 * few m/s², a shipyard low over a gas giant at 71.7. #529 found the assist
 * holding a velocity read once at the top of the step while the frame moved
 * on under it: every step the frame's `a·dt` came back as fresh drift, the
 * lateral damping settled on a lag of `a × assistLateralTauS`, and the
 * shipyard slid sideways past a pilot docking by hand at 0.087 km/s.
 *
 * So the ship's velocity is split against `start` and re-joined at `end`: a
 * ship flying in the frame shares its acceleration, as it would share its
 * gravity. The frame is free-falling, so that makes it the local inertial one,
 * and flight in it is flight in the star's frame (`tests/sim.test.ts`).
 *
 * **Both ends come from one frame.** A caller that switches frame between
 * steps passes the new frame's velocity at both ends of the step it switches
 * on, and a switch then carries nothing — a difference of two bodies'
 * velocities is not an acceleration. Pass `{ start: v, end: v }` for a frame
 * that does not accelerate.
 */
export interface FrameMotion {
	start: Vec3;
	end: Vec3;
}

/** A frame that does not accelerate across the step: the same velocity at
 *  both ends. */
export const steadyFrame = (vel: Vec3): FrameMotion => ({
	start: vel,
	end: vel,
});

/** The frame's mean velocity across the step: what carries a position
 *  through it, exactly for a frame whose acceleration is steady over one
 *  step (#529). */
export const frameMean = (frame: FrameMotion): Vec3 =>
	scale(add(frame.start, frame.end), 0.5);

/**
 * #5's model, built: assisted Newtonian, with the assist a toggle.
 *
 * **Assist on** — the throttle commands a *speed*, not a thrust: the ship
 * accelerates toward `throttle × ASSIST_CAP_KMS` along the nose at the hull's
 * own `thrustKms2` and holds it, and sideways velocity decays with its
 * `assistLateralTauS`. The cap is the *game's* and the rate is the *hull's*
 * (#181): every ship tops out at 2 km/s and they take different times to get
 * there, which is #26's D5 as the pilot feels it. That
 * is what makes it fly like a modern space sim rather than like 1984: releasing
 * the stick mid-turn settles onto the new heading instead of continuing to
 * drift sideways forever.
 *
 * **Assist off** — thrust along the nose and nothing else. No cap, no damping,
 * no help: velocity and nose disagree permanently, which is the whole reason
 * the map's HUD constraint requires a velocity-vector marker. It is Newtonian
 * **in the frame**: the ship shares the frame's acceleration and never its
 * velocity, so a frame that does not accelerate changes nothing and one on an
 * orbit does not fall away from the ship (#529, the principal's ruling —
 * the acceleration is gravity's, not the computer's).
 *
 * Semi-implicit Euler in both cases — the relative velocity first, then
 * position from the *new* one, carried on the frame's mean across the step
 * (`FrameMotion`). One line's difference from the explicit form, and
 * noticeably better behaved under the varying frame delta a browser gives you.
 *
 * `dt` is passed in rather than read from a clock, so a probe can step this
 * with a fixed delta and get the same answer twice.
 */
export function stepFlight(
	ship: Ship,
	control: FlightControl,
	dt: number,
	perf: FlightPerformance,
): void {
	if (dt <= 0) return;
	const throttle = Math.min(1, Math.max(0, control.throttle));

	// Everything happens in the frame — see `FrameMotion`. The velocity is
	// taken relative to the frame where the step starts and handed back
	// relative to it where the step ends, and the position rides the frame's
	// mean across the step: carrying only the end velocity leaves `a·dt²/2` a
	// step, 430 m in two minutes at `MAX_DT` beside the shipyard.
	const start = control.frame?.start ?? v3();
	const end = control.frame?.end ?? start;
	const carried = frameMean({ start, end });
	const relative = sub(ship.vel, start);
	const next = control.assist
		? assistedRelative(relative, control.nose, throttle, dt, perf)
		: add(relative, scale(control.nose, perf.thrustKms2 * throttle * dt));
	ship.vel = add(end, next);
	ship.pos = add(ship.pos, scale(add(carried, next), dt));
}

/** The assist's step on a velocity relative to the frame: #5's law. */
function assistedRelative(
	relative: Vec3,
	nose: Vec3,
	throttle: number,
	dt: number,
	perf: FlightPerformance,
): Vec3 {
	// Split it about the nose: the component along it is what the throttle
	// governs, and everything perpendicular is drift the assist exists to remove.
	const along = dot(relative, nose);
	const lateral = sub(relative, scale(nose, along));
	const damped = scale(lateral, Math.exp(-dt / perf.assistLateralTauS));

	const want = throttle * ASSIST_CAP_KMS;
	const authority = perf.thrustKms2 * dt;
	const next = along + clamp(want - along, -authority, authority);

	const assisted = add(scale(nose, next), damped);
	// The cap is on the *total*, not on the commanded component: a ship that
	// enters a turn at the cap would otherwise briefly exceed it, since the
	// lateral remainder is still there while it decays.
	const speed = length(assisted);
	return speed > ASSIST_CAP_KMS
		? scale(assisted, ASSIST_CAP_KMS / speed)
		: assisted;
}

const clamp = (v: number, lo: number, hi: number): number =>
	Math.min(hi, Math.max(lo, v));

/**
 * One step of the whole world: the clock, then the bodies, then the ship.
 *
 * The order is the point. Bodies move to the *new* time before the ship
 * integrates against it, so a frame never mixes a body position from one clock
 * value with a ship position from another — which is the sort of half-step
 * error that shows up as a station wobbling rather than as anything obviously
 * broken.
 *
 * `dt` is seconds of **sim** time and is never scaled (#10).
 */
export function stepWorld(
	world: World,
	control: FlightControl,
	dt: number,
	perf: FlightPerformance,
): void {
	const from = { ...world.ship.pos };
	const planetStarts = new Map(
		world.system.bodies
			.filter((body) => body.kind === "planet")
			.map((body) => [body.id, { ...body.pos }]),
	);
	advanceWorldClock(world, dt);
	stepFlight(world.ship, control, dt, perf);
	if (dt <= 0) return;
	let earliest: { time: number; body: Body; start: Vec3 } | null = null;
	for (const body of world.system.bodies) {
		if (body.kind !== "planet") continue;
		const start = planetStarts.get(body.id);
		if (!start) continue;
		const time = planetApproachEntryTime({
			from,
			velocity: scale(sub(world.ship.pos, from), 1 / dt),
			duration: dt,
			centre: start,
			centreVelocity: scale(sub(body.pos, start), 1 / dt),
			radiusKm: body.radiusKm,
		});
		if (time === null || (earliest && time > earliest.time)) continue;
		earliest = { time, body, start };
	}
	if (!earliest) return;
	const carryVelocity = scale(sub(earliest.body.pos, earliest.start), 1 / dt);
	const shipVelocity = scale(sub(world.ship.pos, from), 1 / dt);
	const boundaryPos = add(from, scale(shipVelocity, earliest.time));
	world.ship.pos = add(boundaryPos, scale(carryVelocity, dt - earliest.time));
	world.ship.vel = bodyVelocity(world.system, earliest.body.id, world.gameTime);
}

/**
 * The clock and the bodies, without the ship.
 *
 * Split out because cruise (#10, #14) does not integrate the ship the way
 * `stepFlight` does — it is nose-locked and position-dependent, with its own
 * sub-stepping — but it owes the world the same ordering: bodies at the *new*
 * time before anything reads their positions. Leaving the two lines inlined in
 * `stepWorld` meant the cruise path had to restate them, which is how a second
 * clock gets invented.
 *
 * `dt` is seconds of **sim** time and is never scaled (#10). Cruise is
 * fictional FTL; the world it crosses ticks at real time.
 */
export function advanceWorldClock(world: World, dt: number): void {
	world.gameTime += dt;
	advanceSystem(world.system, world.gameTime);
}

/**
 * Put a world back where `makeWorld` left it, **without regenerating it**.
 *
 * The clock to zero, the bodies to where that clock puts them, the ship back at
 * the arrival point at rest. The same `System` object throughout: same
 * `contents`, same `byId`, same `Body` instances moved in place.
 *
 * ## Why in place, and why here
 *
 * #121 ratified a **ship-state reset within one system** for
 * `probe-arrival.mjs`, which flies two legs on one page and needs the second to
 * start where the first did. A world *rebuild* was ruled out rather than merely
 * not chosen: `Game` calls `makeWorld` exactly once and holds per-system caches
 * that are deliberately never invalidated on that basis — the baked
 * `environmentMap`, and the `interiors` berth catalogue whose own comment says a
 * build that adds a jump owes it a clear. Swapping the system out is that build.
 *
 * It lives in `sim.ts` rather than on the renderer because that is what makes it
 * checkable: `tests/world-reset.test.ts` compares the result against a fresh
 * `makeWorld(seed)`, on the tier that runs on every push. The renderer's own
 * session state — regime, charge, spool, the last exit — is not a world concern
 * and is reset beside this call, guarded separately.
 *
 * **The values are restated rather than copied off a fresh `makeWorld`**, so
 * `tests/world-reset.test.ts` has something to catch. Precisely what it can
 * catch is worth being exact about, because two earlier versions of this
 * comment were not. Both this function and `makeWorld` call the same
 * `arrivalPoint`, so the test cannot disagree about that function's *output*;
 * what it checks is the four arguments, the clock value, whether each field is
 * written at all, and — now that the clock is read back rather than restated —
 * the order of the first two lines. Each of those was confirmed by breaking it
 * and watching the file go red. A reset that built a whole world from
 * `makeWorld` and copied its fields across could fail none of them.
 *
 * `originPos` is `null` and the clock is `0` because that is what a new game is
 * (`makeWorld`); a reset is a return to the new game, not to some later arrival.
 *
 * **It refuses a world that has jumped (#187).** Every line below reads
 * `world.system` — the system the ship is *in* — so after a jump this would put
 * the ship at the arrival point of the wrong star at clock zero, which is a
 * state no boot produces and which the comparison against `makeWorld(seed)`
 * cannot see, because that comparison is written for a world that never left.
 * Returning a jumped world would mean rebuilding the system here, and a rebuild
 * is exactly what this function's own argument above rules out. So it throws,
 * and the renderer's `resetFlightToStart` inherits the limit rather than
 * papering over it.
 *
 * The precondition is **exported as `canResetWorldToStart`** rather than left
 * for a caller to discover by catching. This function went from total to
 * partial, and a partial function whose domain can only be learned from its
 * error message is one every later caller — #89's load, a probe's reset —
 * re-learns the hard way.
 */
export function canResetWorldToStart(world: World): boolean {
	return world.system.record.index === startSystem(world.galaxy).index;
}

export function resetWorldToStart(world: World): void {
	const start = startSystem(world.galaxy);
	world.gameTime = 0;
	// **Total again, and that is sage round 2's correction to this node.** #187
	// first made this throw when the ship was somewhere else, and exported
	// `canResetWorldToStart` so a caller could ask first. But the throw reached
	// the published `window.__seelite.resetFlightToStart()`, so any probe that
	// reset after a jump got an exception instead of a reset — and #89's load
	// path would have inherited the same. A reset that cannot reset is not a
	// narrower contract, it is a broken one.
	//
	// Rebuilding costs one `makeSystem`, which is exactly what `jumpWorldTo`
	// does, so there was never a reason for the partial form. The predicate
	// stays exported because it answers a real question — *is this a rebuild or
	// a rewind* — which a caller wanting to skip the work may still want.
	if (!canResetWorldToStart(world)) world.system = makeSystem(start, 0);
	// `world.gameTime`, not a second literal `0`. With the literal the two lines
	// were independent, so their order was not load-bearing and no swap could go
	// red — while a comment above claimed the ordering had been red-built.
	// Reading the clock back is also `advanceWorldClock`'s own shape, and it
	// leaves one line owning what the time is.
	advanceSystem(world.system, world.gameTime);
	// `world.gameTime` here too, for the reason four lines up: a second literal
	// would be a second statement of what the time is, and the one place that
	// says it should be the line that sets it.
	world.ship.pos = arrivalPoint(
		world.system.record,
		world.system.contents,
		null,
		world.gameTime,
	);
	world.ship.vel = v3();
}
