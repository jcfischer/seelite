/**
 * One station's aperture frame at a clock: `stationPose`'s axis, phase and
 * reference, through `docking.ts`'s one builder. The game's
 * `apertureFrameOf` and the step's station solids both read it.
 *
 * `stationPose` reads the bodies where the system last placed them, so this
 * is the frame *at the system's clock* — call it before `advanceWorldClock`
 * for a step's start and after for its end.
 */
export function stationApertureFrame(
	system: System,
	stationId: string,
	gameTime: number,
): ApertureFrame {
	const pose = stationPose(system, stationId, gameTime);
	return apertureFrame(
		stationOf(system, stationId).type,
		pose.axis,
		pose.phaseRad,
		pose.reference,
	);
}

/** A collision `Impact`, naming the body met by id. */
export interface WorldImpact extends Impact {
	bodyId: string;
}

/**
 * The bodies that are solid in normal flight as a sphere at `radiusKm`: a
 * star, a planet and a moon (`collision.md` §2.1, C1). A station is solid on
 * its proxy instead (§2.2, node #663) and is swept from its own start pose
 * (`StationStart`), and a contact is never a body.
 */
const SOLID_BODY_KINDS: ReadonlySet<BodyKind> = new Set([
	"star",
	"planet",
	"moon",
]);

/**
 * One step of the whole world: the clock, then the bodies, then the ship.
 *
 * The order is the point. Bodies move to the *new* time before the ship
 * integrates against it, so a frame never mixes a body position from one clock
 * value with a ship position from another — which is the sort of half-step
 * error that shows up as a station wobbling rather than as anything obviously
 * broken.
 *
 * The ship is flown by the Hull step, so the player's turn and its push land
 * in the same step as everyone else's (#646).
 *
 * **`solid` turns collision on** (`collision.md`, node #661): the ship's
 * primitives in its own frame — its hull box, `hullBox`. Omitted, the ship
 * meets nothing, which is what a caller passes for a collision-exempt phase
 * (§5) and what every row written before collision still flies. Given, the
 * step's motion — after #514's planet boundary has had its say — is swept
 * against every star, planet and moon sphere and every station's proxy, in
 * the station's rotating frame (node #663), and the ship is left outside what
 * it met. The damage is reported, not applied: `applyDamage` is the caller's,
 * through its one damage path.
 *
 * **`planes` are the aperture planes the step watches** (§4.2, node #663).
 * The earliest event owns the tick: a crossing found by `apertureCrossing`
 * before any impact is handed back as `plane`, with the ship left unresolved
 * for the six checks to place; an impact at or before it wins, and the plane
 * is not crossed this step. Omitted, nothing is watched.
 *
 * **`fleet` are the other ships the step can meet** (§3, C4b, §6; node
 * #664), and a meeting is an event like the others: each ship's first one is
 * read on the unresolved motions (`firstMeetings`) and weighed against its
 * world impacts and, for the player, the plane. A world impact at or before
 * it is resolved first, as before; a meeting strictly first owns the tick —
 * the world is not resolved, the plane is not crossed, the pair is met, and
 * the ship is then swept against the world on the motion the meeting left it,
 * so a world impact the bounce prevents is never billed.
 *
 * `dt` is seconds of **sim** time and is never scaled (#10).
 */
export function stepWorld(
	world: World,
	attitude: HullAttitude,
	control: HullControl,
	dt: number,
	perf: FlightPerformance,
	solid?: readonly Primitive[] | null,
	planes: readonly PlaneWatch[] = [],
	fleet: readonly FleetShip[] = [],
): WorldStep {
	const from = { ...world.ship.pos };
	const fromVel = { ...world.ship.vel };
	const fromTime = world.gameTime;
	// A station's start is its pose as well as its place: the frame is read
	// off the bodies, so it has to be read before they move. Without a solid
	// only the planets are read, for #514's boundary.
	const starts: WorldStarts = solid
		? worldStarts(world.system, fromTime)
		: {
				bodies: new Map(
					world.system.bodies
						.filter((body) => body.kind === "planet")
						.map((body) => [body.id, { ...body.pos }]),
				),
				stations: [],
			};
	advanceWorldClock(world, dt);
	const step = stepHull(world.ship, attitude, control, dt, perf);
	const untouched = (): FleetStep[] =>
		fleet.map((ship) => ({
			id: ship.id,
			pos: ship.motion.end.origin,
			vel: ship.motion.velEnd,
			impacts: [],
			ghosts: [],
		}));
	if (dt <= 0)
		return {
			...step,
			impacts: [],
			ghosts: [],
			plane: null,
			shipImpacts: [],
			fleet: untouched(),
		};
	holdPlanetBoundary(world, from, starts.bodies, dt);
	const found = crossedPlane(world, planes, step, dt);
	if (!solid)
		return {
			...step,
			impacts: [],
			ghosts: [],
			plane: found,
			shipImpacts: [],
			fleet: untouched(),
		};
	const playerMotion = (): ShipMotion => ({
		massT: perf.massT,
		primitives: solid,
		start: shipPose(from, attitude.nose, attitude.up),
		end: shipPose(world.ship.pos, step.nose, step.up),
		velStart: fromVel,
		velEnd: world.ship.vel,
	});
	// §4.2's earliest event owns the tick, ships included (node #664): when
	// every ship's first meeting with another ship falls, read on the step's
	// own motions before anything has resolved them, so it can be weighed
	// against the world's impacts and the plane before either is committed.
	const shipS = firstMeetings(playerMotion(), fleet, dt);
	const fleetWorld = fleetAgainstWorld(world, fleet, starts, shipS.fleet, {
		fromTime,
		dt,
	});
	// The player's world sweep is cut off at the earlier of the plane and its
	// first ship meeting. Neither the world nor the plane before the cut, the
	// cut owns the tick: the plane if it came strictly first, else the ship
	// (the tie to the meeting, as to an impact).
	const cutS = earliestOf(found ? found.timeS : null, shipS.player);
	const met = collideShip(world, solid, from, fromVel, attitude, step, starts, {
		fromTime,
		dt,
		planeS: cutS,
	});
	const planeOwns =
		met.planeOwns &&
		found !== null &&
		(shipS.player === null || found.timeS < shipS.player);
	// A ship met first: the world is not resolved yet, and the plane is not
	// crossed this step.
	const playerDeferred = met.planeOwns && !planeOwns;
	// The plane owns the tick: the ship is left unresolved for the six checks
	// to place, and no ship was met before it, so it meets none this step.
	const ships = collidePairs(
		world,
		planeOwns ? null : playerMotion(),
		fleet,
		fleetWorld,
		dt,
	);
	// Where the pairs left every ship, before the world's second look.
	const paired = {
		player: { ...world.ship.pos },
		fleet: ships.fleet.map((ship) => ({ ...ship.pos })),
	};
	// What the first meeting left a deferred ship on, it now meets the world
	// along: swept again from the step's start to where the pair left it.
	let { impacts, ghosts } = met;
	if (playerDeferred) {
		const after = collideShip(
			world,
			solid,
			from,
			fromVel,
			attitude,
			step,
			starts,
			{ fromTime, dt, planeS: null },
		);
		impacts = after.impacts;
		ghosts = [...new Set([...ghosts, ...after.ghosts])];
	}
	resweepDeferred(world, fleet, fleetWorld, ships.fleet, starts, {
		fromTime,
		dt,
	});
	keepPairsApart(
		planeOwns
			? null
			: { motion: playerMotion(), paired: paired.player, ship: world.ship },
		fleet,
		ships.fleet,
		paired.fleet,
		ships.ghosts,
	);
	return {
		...step,
		impacts,
		ghosts,
		plane: planeOwns ? found : null,
		shipImpacts: ships.player,
		fleet: ships.fleet,
	};
}

/**
 * The fleet's half of a step with no player in it (`collision.md` §3, C4b,
 * §6; node #664): every flown fleet ship against the world, and the fleet's
 * pairs against each other, by the passes `stepWorld` runs — first
 * meetings, the world up to each ship's first meeting, the pairs, the world
 * again for a ship its meeting deferred, and the pairs kept apart. For a
 * frame the player does not fly in normal flight: in cruise the raider and
 * the engaged carriers still fly, and still meet what they fly into.
 *
 * `starts` is the world at the top of the step (`worldStarts`, read before
 * the clock moved); the world now stands at the step's end. Nothing is
 * resolved against the player, who is not in this step's pairs.
 */
export function stepFleet(
	world: World,
	fleet: readonly FleetShip[],
	starts: WorldStarts,
	clock: { fromTime: number; dt: number },
): FleetStep[] {
	// As `stepWorld`: a step of no time sweeps nothing, and every ship is
	// where its own step left it.
	if (clock.dt <= 0)
		return fleet.map((ship) => ({
			id: ship.id,
			pos: ship.motion.end.origin,
			vel: ship.motion.velEnd,
			impacts: [],
			ghosts: [],
		}));
	const shipS = firstMeetings(null, fleet, clock.dt);
	const fleetWorld = fleetAgainstWorld(
		world,
		fleet,
		starts,
		shipS.fleet,
		clock,
	);
	const ships = collidePairs(world, null, fleet, fleetWorld, clock.dt);
	const paired = ships.fleet.map((ship) => ({ ...ship.pos }));
	resweepDeferred(world, fleet, fleetWorld, ships.fleet, starts, clock);
	keepPairsApart(null, fleet, ships.fleet, paired, ships.ghosts);
	return ships.fleet;
}

/** The earlier of two times into a step, either of which may be absent. */
const earliestOf = (a: number | null, b: number | null): number | null =>
	a === null ? b : b === null ? a : Math.min(a, b);

/**
 * When each ship's step first meets another ship (§4.2, node #664), read on
 * the step's own motions — nothing resolved yet — through the pairs
 * `collidePairs` will take: the player against every fleet ship, and every
 * fleet pair with one flown, a projected carrier as B. A billed meeting is at
 * its own time; a resting hold with nothing billed is at the start of the
 * step for a ship it stopped closing — its velocity changed — and is no
 * meeting at all for one it only nudged along a graze. `null` where a ship
 * meets none.
 *
 * Read-only, and an estimate past the first event: a ship that meets the
 * world before it meets its partner leaves that line, so the partner's time
 * may be one the step never reaches. That errs safe — a ship whose world
 * sweep is deferred for a meeting that does not happen is swept again on the
 * motion it keeps (`resweepDeferred`), and meets the same world.
 */
function firstMeetings(
	player: ShipMotion | null,
	fleet: readonly FleetShip[],
	dt: number,
): { player: number | null; fleet: (number | null)[] } {
	let you: number | null = null;
	const them: (number | null)[] = fleet.map(() => null);
	const pair = (
		a: ShipMotion,
		b: ShipMotion,
		bProjected: boolean,
	): { a: number | null; b: number | null } => {
		const met = sweepShipPair(a, b, dt, { bProjected });
		if (met.impacts.length > 0) {
			const s = Math.min(...met.impacts.map((impact) => impact.timeS));
			return { a: s, b: s };
		}
		return {
			a: length(sub(met.a.vel, a.velEnd)) > 0 ? 0 : null,
			b: length(sub(met.b.vel, b.velEnd)) > 0 ? 0 : null,
		};
	};
	if (player)
		fleet.forEach((ship, index) => {
			const met = pair(player, ship.motion, ship.projected);
			you = earliestOf(you, met.a);
			them[index] = earliestOf(them[index], met.b);
		});
	for (const [x, y] of eligibleFleetPairs(fleet)) {
		const met = pair(fleet[x].motion, fleet[y].motion, fleet[y].projected);
		them[x] = earliestOf(them[x], met.a);
		them[y] = earliestOf(them[y], met.b);
	}
	return { player: you, fleet: them };
}

/**
 * Every pair of fleet ships the step meets (§6, node #664), by index: at
 * least one flown — two projected carriers are never paired, because a route
 * against a route is the corpus row's (§6 item 1) — and a projected carrier
 * always second, as the pair's B, so a hold it cannot take goes to the ship
 * that can. One list for every pass that pairs the fleet (`firstMeetings`,
 * `collidePairs`, `keepPairsApart`), so they cannot disagree about which
 * pairs there are or which ship is B.
 */
function eligibleFleetPairs(fleet: readonly FleetShip[]): [number, number][] {
	const pairs: [number, number][] = [];
	for (let i = 0; i < fleet.length; i++)
		for (let j = i + 1; j < fleet.length; j++) {
			if (fleet[i].projected && fleet[j].projected) continue;
			pairs.push(fleet[i].projected ? [j, i] : [i, j]);
		}
	return pairs;
}

/**
 * Every flown fleet ship whose world sweep its first ship meeting deferred
 * (`fleetAgainstWorld`), swept against the world again on what the pairs left
 * it (§4.2, node #664): from the step's start to the end and velocity the
 * meeting gave it, so a bounce that turned it off a solid meets nothing and
 * one that left it inside a solid is held outside. A straight line from the
 * start to the corrected end stands for the bent path, which is exact for a
 * meeting at the start of the step and an approximation for one later. Its
 * world impacts follow its ship meetings, which came first.
 */
function resweepDeferred(
	world: World,
	fleet: readonly FleetShip[],
	againstWorld: { motions: ShipMotion[]; deferred: boolean[] },
	steps: FleetStep[],
	starts: WorldStarts,
	clock: { fromTime: number; dt: number },
): void {
	fleet.forEach((ship, index) => {
		if (!againstWorld.deferred[index]) return;
		const out = steps[index];
		const motion: ShipMotion = {
			...againstWorld.motions[index],
			end: { ...ship.motion.end, origin: out.pos },
			velEnd: out.vel,
		};
		const after = sweepWorld(world, motion, starts, clock, null);
		out.pos = after.pos;
		out.vel = after.vel;
		out.ghosts = [...new Set([...out.ghosts, ...after.ghosts])];
		out.impacts.push(...after.impacts);
	});
}

/**
 * One flown ship's motion against the world: `worldSolids` from `starts`,
 * swept with `sweepShip`, cut off at `cutS` (§4.2). `deferred` when nothing
 * in the world came at or before the cut, which leaves the motion unresolved.
 */
function sweepWorld(
	world: World,
	motion: ShipMotion,
	starts: WorldStarts,
	clock: { fromTime: number; dt: number },
	cutS: number | null,
): {
	pos: Vec3;
	vel: Vec3;
	impacts: ShipImpact[];
	ghosts: string[];
	deferred: boolean;
} {
	const { owner, motions: solids } = worldSolids(
		world.system,
		{
			start: motion.start.origin,
			end: motion.end.origin,
			reachKm: reachKm(motion.primitives),
		},
		starts,
		{ fromTime: clock.fromTime, toTime: world.gameTime },
	);
	if (solids.length === 0)
		return {
			pos: motion.end.origin,
			vel: motion.velEnd,
			impacts: [],
			ghosts: [],
			deferred: cutS !== null,
		};
	const swept = sweepShip(motion, solids, clock.dt, { planeS: cutS });
	return {
		pos: swept.pos,
		vel: swept.vel,
		ghosts: [...new Set(swept.ghosts.map((i) => owner[i]))],
		impacts: swept.impacts.map((impact) => ({
			with: owner[impact.solid],
			ship: false,
			closingKms: impact.closingKms,
			damage: impact.damage,
			side: impact.side,
			resting: impact.resting,
		})),
		deferred: swept.planeOwns,
	};
}

/**
 * Every flown fleet ship against the world (`collision.md` §3, §6; node
 * #664) — the same `worldSolids` the player meets, from the same starts, so a
 * raider meets a planet and a station's proxy exactly as the player does. A
 * projected carrier is not: its pose is a route's, and cannot be bounced.
 *
 * **Cut off at each ship's first ship meeting** (`shipS`, §4.2): a world
 * impact at or before it owns the tick and is resolved here; with none, the
 * ship is `deferred` — left on its own motion for the pairs, and swept again
 * on what they left it (`resweepDeferred`). Each ship's motion comes back
 * ending where its world meeting, if any, left it, for the pairs to sweep.
 */
function fleetAgainstWorld(
	world: World,
	fleet: readonly FleetShip[],
	starts: WorldStarts,
	shipS: readonly (number | null)[],
	clock: { fromTime: number; dt: number },
): { steps: FleetStep[]; motions: ShipMotion[]; deferred: boolean[] } {
	const steps: FleetStep[] = [];
	const motions: ShipMotion[] = [];
	const deferred: boolean[] = [];
	fleet.forEach((ship, index) => {
		const out: FleetStep = {
			id: ship.id,
			pos: ship.motion.end.origin,
			vel: ship.motion.velEnd,
			impacts: [],
			ghosts: [],
		};
		let held = false;
		if (!ship.projected) {
			const met = sweepWorld(world, ship.motion, starts, clock, shipS[index]);
			out.pos = met.pos;
			out.vel = met.vel;
			out.ghosts = met.ghosts;
			out.impacts.push(...met.impacts);
			held = met.deferred;
		}
		steps.push(out);
		deferred.push(held);
		motions.push({
			...ship.motion,
			end: { ...ship.motion.end, origin: out.pos },
			velEnd: out.vel,
		});
	});
	return { steps, motions, deferred };
}

/**
 * The step's ships against each other (`collision.md` §3, C4b, §6; node
 * #664), after each has met whatever of the world came before its first
 * meeting (`fleetAgainstWorld`); a ship whose meeting came first meets the
 * world after this, on what the pair left it (`resweepDeferred`).
 *
 * **The player against every fleet ship**, then **every pair of fleet ships**
 * with at least one flown — through `sweepShipPair`, so momentum is
 * conserved, the impulse is split by `massT`, and both take the same damage
 * on their own sides. A resting hold with nothing billed still lands where
 * it left both ships, so a touching pair is never left overlapped. A
 * projected carrier is always the pair's B (`bProjected`), so a hold it
 * cannot take goes to the ship that can. Two projected carriers are never
 * paired: a route against a route is the corpus row's (§6 item 1).
 *
 * Pairs are resolved in that order, each from the state the one before left,
 * which is exact for one meeting a step and an ordering for more.
 */
function collidePairs(
	world: World,
	player: ShipMotion | null,
	fleet: readonly FleetShip[],
	againstWorld: { steps: FleetStep[]; motions: ShipMotion[] },
	dt: number,
): { player: ShipImpact[]; fleet: FleetStep[]; ghosts: Set<string> } {
	const shipImpacts: ShipImpact[] = [];
	const ghosts = new Set<string>();
	const { steps } = againstWorld;
	const motions = [...againstWorld.motions];
	/** One side of a pair: its motion, its name, whether it is a carrier on
	 *  its projection, and where the pair left it and what it met, if
	 *  anything. */
	interface Side {
		motion: ShipMotion;
		id: string;
		projected: boolean;
		land: (pos: Vec3, vel: Vec3, impact: ShipImpact | null) => void;
	}
	/** One pair, A then B, each landing where it ends and what it met. Only B
	 *  may be projected (`eligibleFleetPairs`). */
	const meet = (A: Side, B: Side): { a: ShipMotion; b: ShipMotion } => {
		const a = A.motion;
		const b = B.motion;
		const pair = sweepShipPair(a, b, dt, { bProjected: B.projected });
		if (pair.ghost) ghosts.add(pairKey(A.id, B.id));
		const moved =
			pair.impacts.length > 0 ||
			length(sub(pair.a.pos, a.end.origin)) > 0 ||
			length(sub(pair.b.pos, b.end.origin)) > 0;
		if (!moved) return { a, b };
		A.land(pair.a.pos, pair.a.vel, null);
		B.land(pair.b.pos, pair.b.vel, null);
		for (const impact of pair.impacts) {
			const common = {
				ship: true,
				closingKms: impact.closingKms,
				damage: impact.damage,
				resting: impact.resting,
			};
			A.land(pair.a.pos, pair.a.vel, {
				...common,
				with: B.id,
				side: impact.sideA,
			});
			B.land(pair.b.pos, pair.b.vel, {
				...common,
				with: A.id,
				side: impact.sideB,
			});
		}
		return {
			a: { ...a, end: { ...a.end, origin: pair.a.pos }, velEnd: pair.a.vel },
			b: { ...b, end: { ...b.end, origin: pair.b.pos }, velEnd: pair.b.vel },
		};
	};
	const fleetSide = (index: number): Side => ({
		motion: motions[index],
		id: fleet[index].id,
		projected: fleet[index].projected,
		land: (pos, vel, impact) => {
			steps[index].pos = pos;
			steps[index].vel = vel;
			if (impact) steps[index].impacts.push(impact);
		},
	});
	let you = player;
	fleet.forEach((_, index) => {
		if (!you) return;
		const met = meet(
			{
				motion: you,
				id: PLAYER_SHIP_ID,
				projected: false,
				land: (pos, vel, impact) => {
					world.ship.pos = pos;
					world.ship.vel = vel;
					if (impact) shipImpacts.push(impact);
				},
			},
			fleetSide(index),
		);
		you = met.a;
		motions[index] = met.b;
	});
	for (const [x, y] of eligibleFleetPairs(fleet)) {
		const met = meet(fleetSide(x), fleetSide(y));
		motions[x] = met.a;
		motions[y] = met.b;
	}
	return { player: shipImpacts, fleet: steps, ghosts };
}

/** One pair's name, A then B, for the ghosts `collidePairs` found. */
const pairKey = (idA: string, idB: string): string => `${idA}\u0000${idB}`;

/**
 * Every met pair the world's second look left overlapped, pushed apart again
 * (§3.1, §4.3; node #664). A ship swept against the world after its meeting
 * (`resweepDeferred`, and the player's own resweep) can be held out of a
 * solid **back into the partner it had just parted from**: a raider ramming a
 * patrol against a star pushes the patrol in by the mass split, and the star
 * holds it out again, onto the raider. Left there, the next step would read
 * the pair as overlapped at the start — a ghost (§4.3) — and test it no more.
 *
 * So each pair now overlapped is moved apart along the normal it parted on
 * (read at the poses the pairs left, which stood `SEPARATION_KM` apart), by
 * `pushOutAlong`: wholly by the ship the world did not just hold, or by mass
 * when it held both or neither — never a carrier still on its projection,
 * whose pose is a route's — and the inward part of the pair's relative
 * velocity is taken off in the same shares, so momentum is kept between two
 * free ships. A projected carrier this step **met** is not on its projection
 * any more: the meeting hands it to flight at the pose the step leaves it
 * (§6), so it gives way like a flown ship, and a world-held ship it struck
 * is not pushed back into what held it (sage round 5). **Nothing
 * is billed**: the meeting already was. One pass in the pairs' order, so
 * exact for one meeting a step, as `collidePairs` is; a ship it moves is not
 * swept against the world again.
 */
function keepPairsApart(
	player: {
		motion: ShipMotion;
		paired: Vec3;
		ship: { pos: Vec3; vel: Vec3 };
	} | null,
	fleet: readonly FleetShip[],
	steps: FleetStep[],
	pairedFleet: readonly Vec3[],
	ghosts: ReadonlySet<string>,
): void {
	interface Member {
		id: string;
		motion: ShipMotion;
		/** On its projection and met by nothing this step: a route's pose,
		 *  which nothing here may move. The test is the one `Game.landFleet`
		 *  hands a projected carrier to flight on (no impacts, no landing),
		 *  so a carrier moved here is exactly one the game flies from the
		 *  pose this step leaves it; the two change together or the pose is
		 *  thrown away. */
		pinned: boolean;
		/** Where the pairs left it. */
		paired: Vec3;
		/** Where it is now, written back in place. */
		now: { pos: Vec3; vel: Vec3 };
	}
	const members: Member[] = fleet.map((f, index) => ({
		id: f.id,
		motion: f.motion,
		pinned: f.projected && steps[index].impacts.length === 0,
		paired: pairedFleet[index],
		now: steps[index],
	}));
	const pairs = eligibleFleetPairs(fleet);
	if (player) {
		members.push({
			id: PLAYER_SHIP_ID,
			motion: player.motion,
			paired: player.paired,
			pinned: false,
			now: player.ship,
		});
		const you = members.length - 1;
		pairs.unshift(...fleet.map((_, index): [number, number] => [you, index]));
	}
	const boxOf = (m: Member) => {
		const box = m.motion.primitives.find((p) => p.kind === "box");
		if (!box) throw new Error("a ship collides on its hull box (P1)");
		return box;
	};
	const poseOf = (m: Member, origin: Vec3) => ({ ...m.motion.end, origin });
	/** The world moved it after the pairs did. */
	const held = (m: Member) => length(sub(m.now.pos, m.paired)) > 0;
	for (const [x, y] of pairs) {
		const a = members[x];
		const b = members[y];
		// Overlapped at the start, so never met (§4.3): nothing parted them,
		// and nothing here may move either for it.
		if (ghosts.has(pairKey(a.id, b.id))) continue;
		const boxA = boxOf(a);
		const boxB = boxOf(b);
		if (
			!pairSeparation(boxA, poseOf(a, a.now.pos), boxB, poseOf(b, b.now.pos))
				.overlap
		)
			continue;
		const parted = pairSeparation(
			boxA,
			poseOf(a, a.paired),
			boxB,
			poseOf(b, b.paired),
		);
		// From B toward A, as every separation's normal is.
		const n = parted.overlap
			? normalizeOr(
					sub(a.paired, b.paired),
					normalizeOr(sub(a.now.pos, b.now.pos), v3(1, 0, 0)),
				)
			: parted.normal;
		const push = pushOutAlong(
			boxA,
			poseOf(a, a.now.pos),
			boxB,
			poseOf(b, b.now.pos),
			n,
		);
		if (!(push > 0)) continue;
		const freeA = !a.pinned && !held(a);
		const freeB = !b.pinned && !held(b);
		const shareA = b.pinned
			? 1
			: a.pinned
				? 0
				: freeA === freeB
					? b.motion.massT / (a.motion.massT + b.motion.massT)
					: freeA
						? 1
						: 0;
		a.now.pos = add(a.now.pos, scale(n, push * shareA));
		b.now.pos = sub(b.now.pos, scale(n, push * (1 - shareA)));
		const un = dot(sub(a.now.vel, b.now.vel), n);
		if (un < 0) {
			a.now.vel = sub(a.now.vel, scale(n, un * shareA));
			b.now.vel = add(b.now.vel, scale(n, un * (1 - shareA)));
		}
	}
}

/** A station at the top of a step: its place and its aperture frame. */
export interface StationStart {
	station: Station;
	origin: Vec3;
	frame: ApertureFrame;
}

/** Snapshot placed stations before the world clock moves them. Like the plane
 *  search, the collision collector only reads stations with a placed body. */
export function stationStarts(
	system: System,
	gameTime: number,
): StationStart[] {
	return system.contents.stations
		.filter((station) => system.byId.has(station.id))
		.map((station) => ({
			station,
			origin: { ...bodyOf(system, station.id).pos },
			frame: stationApertureFrame(system, station.id, gameTime),
		}));
}

/** A placed station's frame, origin and velocity at the supplied clock. The
 * body's position must already have been advanced to that clock. */
export function stationEndAt(
	system: System,
	id: string,
	gameTime: number,
): StationEnd {
	return {
		frame: stationApertureFrame(system, id, gameTime),
		origin: { ...bodyOf(system, id).pos },
		vel: bodyVelocity(system, id, gameTime),
	};
}

function bodyOf(system: System, id: string): Body {
	const body = system.byId.get(id);
	if (!body) throw new Error(`no placed body ${id}`);
	return body;
}

/**
 * The earliest crossing of a watched plane, from each watch's `before` to
 * where the ship is now — in `stepWorld`, on the step's own motion before any
 * collision has corrected it, because §4.2 weighs the crossing against the
 * impacts on the same motion. The after-pose is the game's `entryPoseOf`: the
 * ship from the station's centre, its velocity relative to the station's, and
 * `attitude`, the one the step turned to. `timeS` is the crossing's fraction
 * of `dt`.
 *
 * Exported for `Game.crossingFrom`, the probes' seam that places a ship on
 * both sides of a plane rather than flying it: one search for both.
 */
export function crossedPlane(
	world: World,
	planes: readonly PlaneWatch[],
	attitude: { nose: Vec3; up: Vec3 },
	dt: number,
): WorldPlane | null {
	let earliest: WorldPlane | null = null;
	for (const watch of planes) {
		const body = world.system.byId.get(watch.stationId);
		if (!body) continue;
		const after: EntryPose = {
			rel: sub(world.ship.pos, body.pos),
			vRel: sub(
				world.ship.vel,
				bodyVelocity(world.system, watch.stationId, world.gameTime),
			),
			nose: attitude.nose,
			up: attitude.up,
		};
		const crossing = apertureCrossing(
			watch.frame,
			watch.before,
			after,
			body.radiusKm,
		);
		if (!crossing) continue;
		const timeS = crossing.fraction * dt;
		if (earliest && timeS >= earliest.timeS) continue;
		earliest = {
			stationId: watch.stationId,
			frame: watch.frame,
			crossing: crossing.pose,
			timeS,
		};
	}
	return earliest;
}

/** #514: normal flight stops at a planet's 1.2-radius boundary, riding with
 *  the planet for the rest of the step. */
function holdPlanetBoundary(
	world: World,
	from: Vec3,
	starts: ReadonlyMap<string, Vec3>,
	dt: number,
): void {
	let earliest: { time: number; body: Body; start: Vec3 } | null = null;
	for (const body of world.system.bodies) {
		if (body.kind !== "planet") continue;
		const start = starts.get(body.id);
		if (!start) continue;
		const time = planetApproachEntryTime({
			from,
			velocity: scale(sub(world.ship.pos, from), 1 / dt),
			duration: dt,
			centre: start,
			centreVelocity: scale(sub(body.pos, start), 1 / dt),
			radiusKm: body.radiusKm,
		});
		if (time === null || (earliest && time > earliest.time)) continue;
		earliest = { time, body, start };
	}
	if (!earliest) return;
	const carryVelocity = scale(sub(earliest.body.pos, earliest.start), 1 / dt);
	const shipVelocity = scale(sub(world.ship.pos, from), 1 / dt);
	const boundaryPos = add(from, scale(shipVelocity, earliest.time));
	world.ship.pos = add(boundaryPos, scale(carryVelocity, dt - earliest.time));
	world.ship.vel = bodyVelocity(world.system, earliest.body.id, world.gameTime);
}

/** The world at the top of a step: every solid body's place, and every
 *  placed station's place and pose. Snapshot before the clock moves. */
export interface WorldStarts {
	bodies: ReadonlyMap<string, Vec3>;
	stations: readonly StationStart[];
}

/** Snapshot `WorldStarts` before the clock moves. */
export function worldStarts(system: System, gameTime: number): WorldStarts {
	return {
		bodies: new Map(
			system.bodies
				.filter((body) => SOLID_BODY_KINDS.has(body.kind))
				.map((body) => [body.id, { ...body.pos }]),
		),
		stations: stationStarts(system, gameTime),
	};
}

/**
 * Every solid one ship's step can reach (`collision.md` §2.1, §2.2): each
 * star, planet and moon sphere, and each station's proxy (node #663), from
 * `starts` to where `system` stands now. A body's velocity is read at both
 * ends of the step only once its bounding sphere can be reached, because
 * `bodyVelocity` walks the contents.
 *
 * A station is two solids where its form has a static keel (the shipyard's):
 * the spinning member, turning through the step's phase change, and the keel
 * on the phase-zero basis — both from `stationMotions`, the one posing. Its
 * bounding sphere is the proxy's own reach, not the body's radius: the Gantry's
 * keel stands 1.66 km out on a 0.6 km core.
 *
 * `owner[i]` names the body `motions[i]` belongs to. One builder for every
 * ship the sim sweeps — the player, a raider, a carrier (node #664) — so a
 * change to what is solid lands once.
 */
export function worldSolids(
	system: System,
	ship: Reach,
	starts: WorldStarts,
	clock: { fromTime: number; toTime: number },
): { owner: string[]; motions: SolidMotion[] } {
	const owner: string[] = [];
	const motions: SolidMotion[] = [];
	for (const body of system.bodies) {
		if (!SOLID_BODY_KINDS.has(body.kind)) continue;
		const start = starts.bodies.get(body.id);
		if (!start) continue;
		if (!mayMeet(ship, { start, end: body.pos, reachKm: body.radiusKm }))
			continue;
		owner.push(body.id);
		motions.push({
			primitives: [bodySphere(body.radiusKm)],
			start: { origin: start, ...IDENTITY_AXES },
			end: { origin: { ...body.pos }, ...IDENTITY_AXES },
			velStart: bodyVelocity(system, body.id, clock.fromTime),
			velEnd: bodyVelocity(system, body.id, clock.toTime),
		});
	}
	for (const { station, origin, frame } of starts.stations) {
		if (!system.byId.has(station.id)) continue;
		const proxy = selectedStationProxy(station);
		const body = bodyOf(system, station.id);
		if (
			!mayMeet(ship, {
				start: origin,
				end: body.pos,
				reachKm: proxyReachKm(proxy),
			})
		)
			continue;
		for (const motion of stationMotions(
			proxy,
			{
				frame,
				origin,
				vel: bodyVelocity(system, station.id, clock.fromTime),
			},
			stationEndAt(system, station.id, clock.toTime),
		)) {
			owner.push(station.id);
			motions.push(motion);
		}
	}
	return { owner, motions };
}

/**
 * The step's ship motion against every solid `worldSolids` names, through
 * `sweepShip`.
 *
 * `clock.planeS` is the watched plane's time (§4.2): the sweep weighs it
 * against every impact, and `planeOwns` says which won.
 */
function collideShip(
	world: World,
	solid: readonly Primitive[],
	from: Vec3,
	fromVel: Vec3,
	attitude: HullAttitude,
	step: HullStep,
	starts: WorldStarts,
	clock: { fromTime: number; dt: number; planeS: number | null },
): { impacts: WorldImpact[]; ghosts: string[]; planeOwns: boolean } {
	const { owner, motions } = worldSolids(
		world.system,
		{ start: from, end: world.ship.pos, reachKm: reachKm(solid) },
		starts,
		{ fromTime: clock.fromTime, toTime: world.gameTime },
	);
	const swept = sweepShip(
		{
			primitives: solid,
			start: shipPose(from, attitude.nose, attitude.up),
			end: shipPose(world.ship.pos, step.nose, step.up),
			velStart: fromVel,
			velEnd: world.ship.vel,
		},
		motions,
		clock.dt,
		{ planeS: clock.planeS },
	);
	world.ship.pos = swept.pos;
	world.ship.vel = swept.vel;
	return {
		impacts: swept.impacts.map((impact) => ({
			...impact,
			bodyId: owner[impact.solid],
		})),
		// A station's spinning member and its keel are one body met.
		ghosts: [...new Set(swept.ghosts.map((index) => owner[index]))],
		planeOwns: swept.planeOwns,
	};
}

/**
 * The clock and the bodies, without the ship.
 *
 * Split out because cruise (#10, #14) does not integrate the ship the way
 * `stepFlight` does — it is nose-locked and position-dependent, with its own
 * sub-stepping — but it owes the world the same ordering: bodies at the *new*
 * time before anything reads their positions. Leaving the two lines inlined in
 * `stepWorld` meant the cruise path had to restate them, which is how a second
 * clock gets invented.
 *
 * `dt` is seconds of **sim** time and is never scaled (#10). Cruise is
 * fictional FTL; the world it crosses ticks at real time.
 */
export function advanceWorldClock(world: World, dt: number): void {
	world.gameTime += dt;
	advanceSystem(world.system, world.gameTime);
}

/**
 * Put a world back where `makeWorld` left it, **without regenerating it**.
 *
 * The clock to zero, the bodies to where that clock puts them, the ship back at
 * the arrival point at rest. The same `System` object throughout: same
 * `contents`, same `byId`, same `Body` instances moved in place.
 *
 * ## Why in place, and why here
 *
 * #121 ratified a **ship-state reset within one system** for
 * `probe-arrival.mjs`, which flies two legs on one page and needs the second to
 * start where the first did. A world *rebuild* was ruled out rather than merely
 * not chosen: `Game` calls `makeWorld` exactly once and holds per-system caches
 * that are deliberately never invalidated on that basis — the baked
 * `environmentMap`, and the `interiors` berth catalogue whose own comment says a
 * build that adds a jump owes it a clear. Swapping the system out is that build.
 *
 * It lives in `sim.ts` rather than on the renderer because that is what makes it
 * checkable: `tests/world-reset.test.ts` compares the result against a fresh
 * `makeWorld(seed)`, on the tier that runs on every push. The renderer's own
 * session state — regime, charge, spool, the last exit — is not a world concern
 * and is reset beside this call, guarded separately.
 *
 * **The values are restated rather than copied off a fresh `makeWorld`**, so
 * `tests/world-reset.test.ts` has something to catch. Precisely what it can
 * catch is worth being exact about, because two earlier versions of this
 * comment were not. Both this function and `makeWorld` call the same
 * `arrivalPoint`, so the test cannot disagree about that function's *output*;
 * what it checks is the four arguments, the clock value, whether each field is
 * written at all, and — now that the clock is read back rather than restated —
 * the order of the first two lines. Each of those was confirmed by breaking it
 * and watching the file go red. A reset that built a whole world from
 * `makeWorld` and copied its fields across could fail none of them.
 *
 * `originPos` is `null` and the clock is `0` because that is what a new game is
 * (`makeWorld`); a reset is a return to the new game, not to some later arrival.
 *
 * **It refuses a world that has jumped (#187).** Every line below reads
 * `world.system` — the system the ship is *in* — so after a jump this would put
 * the ship at the arrival point of the wrong star at clock zero, which is a
 * state no boot produces and which the comparison against `makeWorld(seed)`
 * cannot see, because that comparison is written for a world that never left.
 * Returning a jumped world would mean rebuilding the system here, and a rebuild
 * is exactly what this function's own argument above rules out. So it throws,
 * and the renderer's `resetFlightToStart` inherits the limit rather than
 * papering over it.
 *
 * The precondition is **exported as `canResetWorldToStart`** rather than left
 * for a caller to discover by catching. This function went from total to
 * partial, and a partial function whose domain can only be learned from its
 * error message is one every later caller — #89's load, a probe's reset —
 * re-learns the hard way.
 */
export function canResetWorldToStart(world: World): boolean {
	return world.system.record.index === startSystem(world.galaxy).index;
}

export function resetWorldToStart(world: World): void {
	const start = startSystem(world.galaxy);
	world.gameTime = 0;
	// **Total again, and that is sage round 2's correction to this node.** #187
	// first made this throw when the ship was somewhere else, and exported
	// `canResetWorldToStart` so a caller could ask first. But the throw reached
	// the published `window.__seelite.resetFlightToStart()`, so any probe that
	// reset after a jump got an exception instead of a reset — and #89's load
	// path would have inherited the same. A reset that cannot reset is not a
	// narrower contract, it is a broken one.
	//
	// Rebuilding costs one `makeSystem`, which is exactly what `jumpWorldTo`
	// does, so there was never a reason for the partial form. The predicate
	// stays exported because it answers a real question — *is this a rebuild or
	// a rewind* — which a caller wanting to skip the work may still want.
	if (!canResetWorldToStart(world)) world.system = makeSystem(start, 0);
	// `world.gameTime`, not a second literal `0`. With the literal the two lines
	// were independent, so their order was not load-bearing and no swap could go
	// red — while a comment above claimed the ordering had been red-built.
	// Reading the clock back is also `advanceWorldClock`'s own shape, and it
	// leaves one line owning what the time is.
	advanceSystem(world.system, world.gameTime);
	// `world.gameTime` here too, for the reason four lines up: a second literal
	// would be a second statement of what the time is, and the one place that
	// says it should be the line that sets it.
	world.ship.pos = arrivalPoint(
		world.system.record,
		world.system.contents,
		null,
		world.gameTime,
	);
	world.ship.vel = v3();
}
