/**
 * The Galaxy Map finder's facility surface, captured for a person to look at.
 *
 * **The canonical view set does not reach this node.** Its twenty views are
 * rendered scenes — cockpit, station, planet, berth — and #275's surface is the
 * navigation console's DOM: the finder's rows, their last-known annotations, the
 * unchecked-fence line, and the selected-system record card. A view-set run
 * produces twenty frames none of which contain any of it, so this captures the
 * console instead, at both of §5.2.1's widths.
 *
 * It is a **shot** script and not a probe: nothing here asserts. `CLAUDE.md`'s
 * third tier is a person saying yes, and a probe cannot fail on *this reads
 * wrong* — #35 and #36 both closed green and produced the look #98 then set out
 * to change.
 *
 *   npm run dev                       # in one shell
 *   node scripts/shot-facilities.mjs  # in another
 *   open probe-shots/facilities/index.html
 *
 * Unlike `npm run views` this does not need a GPU: the subject is text and
 * layout, and SwiftShader draws a DOM panel exactly as a real driver does. The
 * chart behind it is incidental to every frame here.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { bootedGame, guardedOrigin, launchChromium } from "./probe-guard.mjs";

const ORIGIN = process.env.PROBE_ORIGIN ?? "http://localhost:5173";
/** `probe-shots/` is gitignored as "regenerated by scripts/shot-*.mjs, never
 *  reviewed as source", which is exactly what this is. */
const OUT = join("probe-shots", "facilities");
mkdirSync(OUT, { recursive: true });

const origin = await guardedOrigin(ORIGIN, [
	"src/galaxy-finder.ts",
	"src/knowledge-labels.ts",
]);
const { browser, page } = await launchChromium();
await page.setViewportSize({ width: 1280, height: 760 });
await page.goto(origin, { waitUntil: "load" });
await bootedGame(page);

const settle = () =>
	page.evaluate(
		() =>
			new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r))),
	);

const clickTab = async (name) => {
	await page.evaluate((tab) => {
		document.querySelector(`[data-live-left-tab="${tab}"]`)?.click();
	}, name);
	await page.waitForFunction(() => window.__seeliteGalaxyMap != null);
	await settle();
};

const clearFinder = async () => {
	await page.evaluate(() => {
		const map = window.__seeliteGalaxyMap;
		map.setFinderQuery("");
		map.setFinderBudget(1);
		for (const chip of document.querySelectorAll("[data-map-finder-economy]"))
			if (chip.getAttribute("aria-pressed") === "true")
				map.toggleFinderEconomy(Number(chip.dataset.mapFinderEconomy));
		for (const chip of document.querySelectorAll("[data-map-finder-facility]"))
			if (chip.getAttribute("aria-pressed") === "true") chip.click();
	});
	await settle();
};

const chip = async (name, budget = 9) => {
	await page.evaluate((n) => {
		document.querySelector(`[data-map-finder-facility="${n}"]`)?.click();
	}, name);
	await page.evaluate(
		(b) => window.__seeliteGalaxyMap.setFinderBudget(b),
		budget,
	);
	await settle();
};

const shots = [];
const shot = async (name, note) => {
	const file = join(OUT, `${name}.png`);
	await page.screenshot({ path: file });
	shots.push({ name, note, file: `${name}.png` });
	console.log(`  ${name}  ${note}`);
};

await clickTab("Galaxy Map");

for (const [label, width, height] of [
	["desktop", 1280, 760],
	["narrow", 390, 844],
]) {
	await page.setViewportSize({ width, height });
	await settle();

	await clearFinder();
	await shot(
		`${label}-closed`,
		"the finder closed — §5.2's existing row, unchanged",
	);

	await clearFinder();
	await chip("REFINERY");
	await shot(
		`${label}-refinery`,
		"REFINERY: one annotation line per row, and the row stays active",
	);

	await clearFinder();
	await chip("SHIPYARD");
	await shot(
		`${label}-shipyard`,
		"SHIPYARD: the boot relay's OPERATIONAL · SEEN … beside STATUS UNKNOWN",
	);

	await clearFinder();
	await chip("KNOWN FENCE");
	await shot(
		`${label}-known-fence`,
		"KNOWN FENCE with nothing docked: no known match, and the unchecked count",
	);

	await clearFinder();
	await chip("REFINERY");
	await page.evaluate(() => {
		const map = window.__seeliteGalaxyMap;
		const row = map.state.finder.inBudget[0];
		if (row) map.select(row.index);
	});
	await settle();
	await shot(
		`${label}-record-card`,
		"a selected row: the full roster with exact times and sources",
	);

	await clearFinder();
	await page.evaluate(() => {
		const map = window.__seeliteGalaxyMap;
		map.select(map.state.currentIndex);
	});
	await settle();
	await shot(
		`${label}-record-card-here`,
		"the start system, the one the boot relay observed",
	);
}

await browser.close();

const rows = shots
	.map(
		(s) =>
			`<figure><img src="${s.file}" alt="${s.name}"><figcaption><b>${s.name}</b><br>${s.note}</figcaption></figure>`,
	)
	.join("\n");
writeFileSync(
	join(OUT, "index.html"),
	`<!doctype html><meta charset="utf-8"><title>seelite — #275 facilities</title>
<style>
 body{background:#0b1016;color:#8fb2c9;font:13px/1.5 system-ui,sans-serif;margin:24px}
 h1{font-size:15px;letter-spacing:.08em;text-transform:uppercase;color:#ffe1a9}
 p{max-width:60em}
 figure{margin:0 0 32px}
 img{max-width:100%;border:1px solid #26506e;display:block}
 figcaption{margin-top:6px;font-size:12px}
 b{color:#ffe1a9}
</style>
<h1>seelite — node #275, last-known facilities</h1>
<p>The navigation console at both of §5.2.1's widths. The canonical view set does
not cover this surface: its twenty views are rendered scenes, and this is the
console's DOM. Nothing here is asserted — it is for reading.</p>
${rows}
`,
);
console.log(`\n${shots.length} shots → ${join(OUT, "index.html")}`);
