/**
 * The authoritative world: float64 kilometres, no Three.js, no DOM.
 *
 * ## Why this is its own module
 *
 * The scale research settled that the scene graph is *display only* — nothing
 * reads a position back out of an `Object3D`, because what the renderer holds
 * is a float32 camera-relative shadow of the real number. Keeping the real
 * numbers in a module that cannot import Three.js is how that stays true: an
 * accidental `mesh.getWorldPosition()` in the simulation would not compile
 * here, because there are no meshes.
 *
 * `tests/headless.test.ts` asserts the module loads with no DOM, which is the
 * cheap version of the same claim.
 *
 * ## What this module is now
 *
 * An **adapter**, and deliberately thin. The world is generated by `galaxy.ts`
 * and `system.ts` from `docs/specs/galaxy-generation.md`; nothing about what a
 * system contains is decided here. What this file adds on top of them is the
 * three things a *running* game needs and a generator does not:
 *
 * - a **clock** (`gameTime`), because body positions are `f(systemSeed,
 *   gameTime)` (spec §7.3) and something has to own the *t*;
 * - **colour**, which is scenery rather than spec — `PlacedBody` carries a
 *   radius and no appearance, and the renderer needs one;
 * - a **ship**, integrated in float64 kilometres.
 *
 * The stand-in generator that used to live here — a star, two planets and a
 * station at fixed positions — is gone, along with the constants that pinned
 * the ship 40 km off it. It was replaced rather than kept alongside, because
 * two generators is how a renderer ends up drawing the wrong one.
 *
 * ## What is still a placeholder
 *
 * `stepShip` integrates Newtonian motion with a linear damping term. The
 * flight model resolved to assisted Newtonian (#5) but is not built; the
 * damping constant here was picked so a cube is steerable with a keyboard in a
 * browser, which is not an argument for anything.
 *
 * Orientation deliberately does **not** live here. It is a quaternion the
 * renderer already owns a good type for, and inventing a second quaternion
 * class to keep this module Three-free would be paying a real cost for a
 * boundary that is not under threat — the precision problem is about
 * *positions*, and a unit quaternion has no magnitude to lose precision in.
 */

import {
	type Galaxy,
	type SystemRecord,
	generateGalaxy,
	startSystem,
} from "./galaxy";
import { mix, seededRand } from "./rng";
import {
	type PlacedBody,
	type StationType,
	type SystemContents,
	arrivalPoint,
	generateContents,
	placeBodies,
	velocityOnOrbit,
} from "./system";
import { type Vec3, add, scale, v3 } from "./vec3";

/**
 * What a body is for rendering purposes.
 *
 * The same four kinds `placeBodies` returns, and that is not a coincidence —
 * anything else here would be a second taxonomy to keep in step with the first.
 * `moon` is new to this module: the placeholder had none.
 */
export type BodyKind = PlacedBody["kind"];

export interface Body {
	id: string;
	kind: BodyKind;
	/** Sim-space position, kilometres, float64, star-centred (spec §7.4). */
	pos: Vec3;
	/** Physical radius in kilometres — scaled with the position in the far
	 *  layer, so the two must not drift apart. */
	radiusKm: number;
	/** Base colour. Emissive for a star, diffuse for everything else. */
	color: number;
}

export interface Ship {
	/** Sim-space position, kilometres, float64. */
	pos: Vec3;
	/** Kilometres per second. */
	vel: Vec3;
}

export interface System {
	/** What the galaxy knows about this system: name, polity, position in LY. */
	record: SystemRecord;
	/** Orbits and radii — time-independent. The generator's output, held so the
	 *  clock can be re-read against it every frame rather than regenerating. */
	contents: SystemContents;
	/** Those contents positioned at the world's `gameTime`. */
	bodies: Body[];
	/** The same bodies by id. Built once — the id set is fixed for a system's
	 *  lifetime, and `advanceSystem` runs every frame. */
	byId: Map<string, Body>;
}

export interface World {
	/** The world seed. Every stream in `rng.ts` derives from this one number. */
	seed: number;
	/**
	 * Seconds of simulation since the new game began.
	 *
	 * The authority for where every body is (spec §7.3), which is why it lives
	 * on the world rather than in the renderer's frame loop: a save carries it,
	 * and anything time-varying — market regeneration, legal-status decay —
	 * reads it rather than inventing its own clock.
	 *
	 * Never compressed (#10). Cruise is fictional FTL, not a time-scale hack.
	 */
	gameTime: number;
	/** Galaxy 0, held whole. 256 records is a few hundred kilobytes, and #11's
	 *  map wants exactly this object. */
	galaxy: Galaxy;
	system: System;
	ship: Ship;
}

/** A new game starts in galaxy 0 (spec §5.1). Which system within it is
 *  `startSystem`'s decision, not this module's. */
export const START_GALAXY = 0;

/** Rocky worlds. Picked by eye from the usual terrestrial range — scenery, not
 *  a claim about composition. */
const ROCKY_COLORS = [0xb08050, 0x8fae7a, 0xc0a080, 0x9b6b53, 0x7f8b94];
/** Gas giants: banded pastels, deliberately lighter than the rocky set so the
 *  two read apart at a glance in a system that has both. */
const GIANT_COLORS = [0xd8c49a, 0xc9a26b, 0xb8c4d8, 0xe0d2b4];
/** Moons: grey, and narrow. A moon that read as colourful as its planet would
 *  compete with it for attention it has not earned. */
const MOON_COLORS = [0x9a9a9a, 0xb0aaa4, 0x86867e];
/**
 * Stations by type, so the type is legible before anything else about the
 * station is. #9 owns their actual geometry.
 *
 * Keyed on `StationType`, not on the body id, and the difference is a compile
 * error rather than a style preference: a `Record<string, number>` keyed on ids
 * needs a fallback for the unmatched case, and that fallback silently paints a
 * renamed or newly added station the same grey as a trade post. `Record<
 * StationType, …>` has no unmatched case to fall back from — adding a fourth
 * station type stops the build until this table answers for it.
 */
const STATION_COLORS: Record<StationType, number> = {
	trade: 0x9aa6b2,
	refinery: 0xb08a5a,
	shipyard: 0x8fc0c0,
};

/**
 * A body's colour, from its identity rather than from its draw order.
 *
 * Seeded through `mix(systemSeed, hashId(body.id))` on its own generator rather
 * than drawn from `DOMAIN.BODIES`, and that is the same rule the `ARRIVAL` tag
 * was added for: replaying a stream the generator already consumed correlates
 * the result with whatever that stream produced. Here the consequence would only
 * be ugly rather than wrong, but a private generator costs nothing and needs no
 * argument.
 *
 * **The identity is the id, not the array index.** An earlier version mixed the
 * position in `placeBodies`' output, which is draw order wearing identity's
 * name: a planet gaining a moon shifts every later index and re-colours the rest
 * of the system. The id is stable against exactly that.
 *
 * Takes the whole system rather than four positional arguments — two of which
 * were `number` and adjacent, one slip from silently swapping the seed and the
 * index.
 */
function colorFor(
	body: PlacedBody,
	record: SystemRecord,
	contents: SystemContents,
): number {
	if (body.kind === "star") return contents.star.color;
	if (body.kind === "station") {
		const station = contents.stations.find((s) => s.id === body.id);
		// A body in `placeBodies`' output that is not in `contents` is not a colour
		// problem, it is the two having disagreed about what is in the system — so
		// it throws rather than picking a default and carrying on.
		if (!station) throw new Error(`station ${body.id} is not in the contents`);
		return STATION_COLORS[station.type];
	}
	const rand = seededRand(mix(record.seed, hashId(body.id)));
	if (body.kind === "moon")
		return MOON_COLORS[Math.floor(rand() * MOON_COLORS.length)];
	// Same rule as the station branch, for the same reason. Falling through to
	// the rocky palette on an unmatched id would paint a gas giant as a rocky
	// world and report nothing.
	const planet = contents.planets.find((p) => p.id === body.id);
	if (!planet) throw new Error(`planet ${body.id} is not in the contents`);
	const palette = planet.isGasGiant ? GIANT_COLORS : ROCKY_COLORS;
	return palette[Math.floor(rand() * palette.length)];
}

/**
 * A body id as a number, for `mix`.
 *
 * FNV-1a, because it needs to be a stable function of the string and nothing
 * more — this feeds a colour, not a position, and no property of the world
 * depends on its distribution.
 */
function hashId(id: string): number {
	let h = 0x811c9dc5;
	for (let i = 0; i < id.length; i++) {
		h ^= id.charCodeAt(i);
		h = Math.imul(h, 0x01000193);
	}
	return h >>> 0;
}

/** Generate a system's contents and position them at `gameTime`. */
export function makeSystem(record: SystemRecord, gameTime: number): System {
	const contents = generateContents(record);
	const bodies = placeBodies(contents, gameTime).map((b) => ({
		id: b.id,
		kind: b.kind,
		pos: b.pos,
		radiusKm: b.radiusKm,
		color: colorFor(b, record, contents),
	}));
	return {
		record,
		contents,
		bodies,
		byId: new Map(bodies.map((b) => [b.id, b])),
	};
}

/**
 * Move a system's bodies to where they are at `gameTime`.
 *
 * Positions are overwritten in place rather than the array being rebuilt, and
 * the reason is the renderer: it holds one mesh per body id, so a fresh array
 * every frame would either force a lookup per body or invite the id-to-mesh map
 * to drift.
 *
 * **Written by id, not by index.** The index form was a positional contract
 * between two modules enforced only by a test — a `placeBodies` that ever
 * filtered or sorted its output (skipping a destroyed station, say) would keep
 * running and assign positions to the wrong bodies, which reads on screen as
 * planets teleporting rather than as an error. Keying by id makes that a throw.
 *
 * The lookup is built **once**, in `makeSystem`, not per frame: the id set is
 * fixed for the lifetime of a system, so rebuilding a `Map` sixty times a second
 * would be paying for a structure that never changes.
 */
export function advanceSystem(system: System, gameTime: number): void {
	const placed = placeBodies(system.contents, gameTime);
	if (placed.length !== system.byId.size) {
		throw new Error(
			`placeBodies returned ${placed.length} bodies, system holds ${system.byId.size}`,
		);
	}
	for (const p of placed) {
		const body = system.byId.get(p.id);
		if (!body) throw new Error(`placeBodies produced unknown body ${p.id}`);
		body.pos = p.pos;
	}
}

/**
 * How fast a body is moving through sim space, km/s.
 *
 * Composed the same way `placeBodies` composes positions — a station's velocity
 * is its parent planet's plus its own around it — because the two have to agree
 * or the ship would be told to match a frame the body is not in.
 *
 * Here rather than in `system.ts` because it needs the *contents* to resolve a
 * parent, which is what this module already holds; `system.ts` supplies the
 * per-orbit derivative and this composes it. The star does not move: system
 * frames are star-centred (spec §7.4), so its velocity is zero by construction
 * rather than by measurement.
 */
export function bodyVelocity(
	system: System,
	id: string,
	gameTime: number,
): Vec3 {
	const { contents } = system;
	if (id === contents.star.id) return v3();
	const planet = contents.planets.find((p) => p.id === id);
	if (planet) return velocityOnOrbit(planet.orbit, gameTime);
	for (const p of contents.planets) {
		const moon = p.moons.find((m) => m.id === id);
		if (moon) {
			return add(
				velocityOnOrbit(p.orbit, gameTime),
				velocityOnOrbit(moon.orbit, gameTime),
			);
		}
	}
	const station = contents.stations.find((s) => s.id === id);
	if (station) {
		const own = velocityOnOrbit(station.orbit, gameTime);
		if (!station.parentId) return own;
		const parent = contents.planets.find((p) => p.id === station.parentId);
		// A parent that is not in the contents is the two having disagreed about
		// what is in the system, which is the same throw `colorFor` makes rather
		// than quietly returning a velocity in the wrong frame.
		if (!parent)
			throw new Error(`station ${id} orbits unknown ${station.parentId}`);
		return add(velocityOnOrbit(parent.orbit, gameTime), own);
	}
	throw new Error(`no body ${id} in this system`);
}

export function makeWorld(seed: number): World {
	const galaxy = generateGalaxy(seed, START_GALAXY);
	const record = startSystem(galaxy);
	const system = makeSystem(record, 0);
	return {
		seed,
		gameTime: 0,
		galaxy,
		system,
		ship: { pos: arrivalPoint(record, system.contents, null, 0), vel: v3() },
	};
}

/**
 * Linear damping, per second, applied to the ship's velocity.
 *
 * **Not the flight model.** #5 resolved on assisted Newtonian with the assist a
 * player toggle; none of that is built. This constant exists so a cube can be
 * steered with a keyboard until it is, and the flight-model implementation is
 * free to delete it.
 */
export const SHIP_DAMPING = 0.6;

/**
 * Advance the ship by `dt` seconds under an acceleration in km/s².
 *
 * Semi-implicit Euler — velocity first, then position from the *new* velocity.
 * It is one line different from the explicit form and noticeably better
 * behaved under a varying frame delta, which is what a browser gives you.
 *
 * `dt` is passed in rather than read from a clock, so a probe can step this
 * with a fixed delta and get the same answer twice. A simulation that reads
 * wall time inside itself is one that cannot be replayed, whatever its seed.
 */
export function stepShip(ship: Ship, accel: Vec3, dt: number): void {
	const damp = Math.max(0, 1 - SHIP_DAMPING * dt);
	ship.vel = scale(add(ship.vel, scale(accel, dt)), damp);
	ship.pos = add(ship.pos, scale(ship.vel, dt));
}

/**
 * One step of the whole world: the clock, then the bodies, then the ship.
 *
 * The order is the point. Bodies move to the *new* time before the ship
 * integrates against it, so a frame never mixes a body position from one clock
 * value with a ship position from another — which is the sort of half-step
 * error that shows up as a station wobbling rather than as anything obviously
 * broken.
 *
 * `dt` is seconds of **sim** time and is never scaled (#10).
 */
export function stepWorld(world: World, accel: Vec3, dt: number): void {
	advanceWorldClock(world, dt);
	stepShip(world.ship, accel, dt);
}

/**
 * The clock and the bodies, without the ship.
 *
 * Split out because cruise (#10, #14) does not integrate the ship the way
 * `stepShip` does — it is nose-locked and position-dependent, with its own
 * sub-stepping — but it owes the world the same ordering: bodies at the *new*
 * time before anything reads their positions. Leaving the two lines inlined in
 * `stepWorld` meant the cruise path had to restate them, which is how a second
 * clock gets invented.
 *
 * `dt` is seconds of **sim** time and is never scaled (#10). Cruise is
 * fictional FTL; the world it crosses ticks at real time.
 */
export function advanceWorldClock(world: World, dt: number): void {
	world.gameTime += dt;
	advanceSystem(world.system, world.gameTime);
}
