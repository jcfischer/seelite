/**
 * The lexicon's words as Kokoro's IPA (#604), into `src/voice-ipa.ts`.
 *
 *   node scripts/build-voice-ipa.mjs
 *
 * **Build time only.** `phonemizer` carries eSpeak NG (GPL-3.0) compiled to
 * WebAssembly; it is a devDependency and runs here, and only the phoneme
 * strings it prints reach the bundle. Kokoro's symbol table is read from the
 * tokenizer the model ships (fetched by `fetch-voice-model.mjs`'s cache or
 * passed as the first argument). Run it after adding a word to
 * `speech-lexicon.ts`; `tests/voice-model.test.ts` goes red until you do.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { phonemize } from "phonemizer";
import { MODEL_REVISION, MODEL_REPO } from "./lib/voice-model.mjs";
const lexPath = "src/speech-lexicon.ts";
const out = "src/voice-ipa.ts";
const tokArg = process.argv[2];
const src = readFileSync(lexPath, "utf8");
const words = [...src.matchAll(/^\t([A-Z]+): "/gm)].map((m) => m[1]);
const fix = (s) =>
	s.replace(/ʲ/g, "j").replace(/r/g, "ɹ").replace(/x/g, "k").replace(/ɬ/g, "l");
const us = {},
	gb = {};
for (const w of words) {
	us[w] = fix((await phonemize(w.toLowerCase(), "en-us")).join(" ").trim());
	gb[w] = fix((await phonemize(w.toLowerCase(), "en")).join(" ").trim());
}
const tokenizer = tokArg
	? JSON.parse(readFileSync(tokArg, "utf8"))
	: await (
			await fetch(
				`https://huggingface.co/${MODEL_REPO}/resolve/${MODEL_REVISION}/tokenizer.json`,
			)
		).json();
const vocab = tokenizer.model.vocab;
const ts = `/**
 * Generated by \`scripts/build-voice-ipa.mjs\` (#604): the lexicon's words as
 * Kokoro's IPA, by eSpeak NG through \`phonemizer\`, which runs only when this
 * file is made — eSpeak (GPL-3.0) is never in the bundle, only its output.
 * \`US\` for the American voices, \`GB\` for the British; and Kokoro's symbol
 * table. Regenerate rather than edit.
 */
export const IPA_US: Readonly<Record<string, string>> = ${JSON.stringify(us, null, "\t")};
export const IPA_GB: Readonly<Record<string, string>> = ${JSON.stringify(gb, null, "\t")};
export const KOKORO_VOCAB: Readonly<Record<string, number>> = ${JSON.stringify(vocab)};
`;
writeFileSync(out, ts);
console.log(
	words.length,
	"words;",
	"GRANTED us",
	us.GRANTED,
	"gb",
	gb.GRANTED,
	"BERTH",
	us.BERTH,
);
